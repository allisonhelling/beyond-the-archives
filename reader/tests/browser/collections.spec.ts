import { expect, test } from '@playwright/test'
import { fixture } from '../../../tests/e2e/library-transport-fixture'
import { organizerAccount, testOrganizer, owner } from './account-fixture'
import { importBook } from './library-fixture'

for (const width of [390, 1280]) test(`shares organizer collection creation, editing and memberships at ${width}px`, async ({ page, context }) => {
 await page.setViewportSize({ width, height: 844 })
 await organizerAccount(context)
 const tables = await fixture(page, { backend: testOrganizer.url, reader: true })
 await page.route('**/rest/v1/rpc/reader_organizer_connection', route => route.fulfill({ json: { enabled: true, userId: owner, secret: 'a'.repeat(64) } }))
 tables.works.push({ id: 'work-8001', ao3_work_id: 8001, verified_chapters: {} })
 tables.library_entries.push({ id: 'entry-8001', work_id: 'work-8001', original_url: 'https://archiveofourown.org/works/8001', reading_status: 'to_read', last_read_chapter: 0, notes: '', is_favorite: false, personal_rating: null, metadata_overrides: { title: 'Shared Story', authors: ['Author'], fandoms: [] }, created_at: '2026-10-01T00:00:00Z' })
 await page.route('**/rest/v1/rpc/userscript_library', async route => {
  const input = route.request().postDataJSON()
  await route.fulfill({ json: input.p_action === 'get' ? { entry: { id: 'entry-8001', version: 'v1', status: 'to_read', progress: 0, notes: '', collections: tables.collection_works.filter(link => link.library_entry_id === 'entry-8001').map(link => link.collection_id) }, collections: tables.collections } : {} })
 })
 await page.goto('/')
 await importBook(page, 'Shared Story', undefined, 'Author', 'https://archiveofourown.org/works/8001')
 const shelves = page.getByRole('navigation', { name: 'Library Shelves' })
 await shelves.getByRole('button', { name: 'New Collection', exact: true }).last().click()
 const dialog = page.getByRole('dialog', { name: 'New Collection', exact: true })
 await dialog.getByRole('textbox', { name: 'Name', exact: true }).fill('Shared Collection')
 await dialog.getByRole('button', { name: 'Create Collection', exact: true }).click()
 await expect(dialog).toHaveCount(0)
 expect(tables.collections.some(collection => collection.name === 'Shared Collection')).toBe(true)
 const card = page.locator('.story-card').first()
 await card.getByRole('button', { name: 'Add to Collection', exact: true }).click()
 const membership = page.getByRole('dialog', { name: 'Edit Collections', exact: true })
 await membership.getByRole('checkbox', { name: 'Shared Collection', exact: true }).check()
 await membership.getByRole('button', { name: 'Save Collections', exact: true }).click()
 await expect(membership).toHaveCount(0)
 expect(tables.collection_works).toHaveLength(1)
 await shelves.getByRole('button', { name: 'Shared Collection', exact: true }).click()
 await expect(card).toBeVisible()
 await card.getByRole('button', { name: 'Add to Collection', exact: true }).click()
 await membership.getByRole('checkbox', { name: 'Shared Collection', exact: true }).uncheck()
 await membership.getByRole('button', { name: 'Save Collections', exact: true }).click()
 await expect(membership).toHaveCount(0)
 await expect(page.locator('.story-card')).toHaveCount(0)
 expect(tables.collection_works).toHaveLength(0)
 await shelves.getByRole('button', { name: 'New Collection', exact: true }).last().click()
 await dialog.getByRole('textbox', { name: 'Name', exact: true }).fill('Automatic Favorites')
 await dialog.getByRole('checkbox', { name: 'Automatic Collection', exact: true }).check()
 await dialog.getByRole('button', { name: 'Favorites', exact: true }).click()
 expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
 await dialog.getByRole('button', { name: 'Create Collection', exact: true }).click()
 await expect(dialog).toHaveCount(0)
 expect(tables.collections.find(collection => collection.name === 'Automatic Favorites')?.automatic_rules).toMatchObject({ filters: { favorites: true } })
})
