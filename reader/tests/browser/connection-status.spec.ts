import { expect, test } from '@playwright/test'
import { account, organizerAccount, owner } from './account-fixture'
import { importBook } from './library-fixture'
async function openProfile(page: import('@playwright/test').Page) {
 const trigger=page.getByRole('button',{name:'Profile Menu',exact:true})
 if(await trigger.getAttribute('aria-expanded')!=='true')await trigger.click()
}

test('shows distinct service icons and network state without overflow on mobile, desktop, and dark themes',async({page,context})=>{
 await context.route('**/auth/bridge',route=>route.fulfill({contentType:'text/html',body:'<!doctype html><title>Signed Out</title>'}))
 await page.goto('/');await openProfile(page)
 const box=page.getByRole('group',{name:'Connection Status',exact:true})
 await expect(box.getByRole('button',{name:'Network: Online',exact:true})).toBeVisible()
 await expect(box.getByRole('button',{name:'Cloud: Not Signed In',exact:true})).toBeVisible()
 await expect(box.getByRole('button',{name:'Organizer: Not Connected',exact:true})).toBeVisible()
 await expect(box.locator('[data-service=network] > svg > circle')).toHaveCount(1)
 await expect(box.locator('[data-service=cloud] .lucide-cloud')).toHaveCount(1)
 await expect(box.locator('[data-service=organizer] > svg > path')).toHaveCount(1)
 await expect(box.locator('[data-service=cloud] .connection-status-symbol')).toHaveCount(0)
 await expect(box.locator('[data-service=network] > svg > circle')).toHaveAttribute('fill','currentColor')
 await expect(box.locator('[data-service=organizer] > svg > path')).toHaveAttribute('d','M9 35V16a11 11 0 0 1 22 0v19Z')
 await expect(box.locator('.connection-status-title')).toHaveText(['Network','Cloud','Organizer'])
 await expect(box).toHaveCSS('height','60px')
 await expect(box).toHaveCSS('border-top-width','0px')
 await expect(box).toHaveCSS('border-left-width','0px')
 await expect(box).toHaveCSS('border-right-width','0px')
 await expect(box).toHaveCSS('border-bottom-width','1px')
 for(const width of [320,390,768,1280]){
  await page.setViewportSize({width,height:844})
  await expect(box).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  const bounds=(await box.boundingBox())!
  expect(bounds.x).toBeGreaterThanOrEqual(0)
  expect(bounds.x+bounds.width).toBeLessThanOrEqual(width)
  for(const button of await box.getByRole('button').all()){const control=(await button.boundingBox())!;expect(control.x+control.width).toBeLessThanOrEqual(bounds.x+bounds.width)}
 }
 await page.setViewportSize({width:390,height:844})
 const network=box.getByRole('button',{name:'Network: Online',exact:true})
 await network.hover()
 await expect(page.getByRole('tooltip',{name:/^Network: Online/})).toBeVisible()
 await network.press('Escape')
 await network.click()
 await expect(page.getByRole('tooltip',{name:/^Network: Online/})).toBeVisible()
 await page.mouse.click(4,500)
 await expect(page.getByRole('tooltip',{name:/^Network: Online/})).toBeHidden()
 await page.screenshot({path:'/tmp/reader-connection-status-mobile.png'})
 await page.getByRole('button',{name:'Toggle Dark Mode',exact:true}).click();await openProfile(page)
 await expect(box.locator('[data-service=network]')).toHaveCSS('color','rgb(155, 201, 170)')
 await expect(box.locator('[data-service=cloud]')).toHaveCSS('color','rgb(194, 170, 167)')
 await context.setOffline(true)
 await expect(box.getByRole('button',{name:'Network: Offline',exact:true})).toBeVisible()
 await expect(box.locator('[data-service=network] > svg > circle')).toHaveAttribute('fill','none')
})

test('reports cloud and organizer sync independently while the network stays online and recovers only after successful sync',async({page,context})=>{
 await organizerAccount(context)
 let cloudFail=false,organizerFail=false,holdCloud=true,releaseCloud:(()=>void)|undefined
 await page.route('**/rest/v1/rpc/reader_organizer_connection',route=>route.fulfill({json:{enabled:true,userId:owner,secret:'a'.repeat(64)}}))
 await page.route('**/rest/v1/reader_cloud_values*',async route=>{
  if(holdCloud){holdCloud=false;await new Promise<void>(resolve=>{releaseCloud=resolve})}
  return cloudFail?route.fulfill({status:500,json:{code:'57014',message:'Cloud statement timed out'}}):route.fulfill({json:[]})
 })
 await page.route('**/rest/v1/rpc/userscript_library',route=>organizerFail?route.fulfill({status:500,json:{message:'Organizer statement timed out'}}):route.fulfill({json:{}}))
 await page.goto('/');await openProfile(page)
 const box=page.getByRole('group',{name:'Connection Status',exact:true})
 await expect(box.getByRole('button',{name:'Cloud: Syncing',exact:true})).toBeVisible()
 await expect(box.locator('[data-service=cloud] .connection-status-icon .lucide-refresh-cw')).toHaveClass(/loading-icon/)
 await page.emulateMedia({reducedMotion:'reduce'})
 await expect(box.locator('[data-service=cloud] .loading-icon')).toHaveCSS('animation-name','none')
 await page.emulateMedia({reducedMotion:'no-preference'})
 await expect.poll(()=>Boolean(releaseCloud)).toBe(true)
 releaseCloud?.()
 await expect(box.getByRole('button',{name:'Cloud: Up to Date',exact:true})).toBeVisible()
 await expect(box.getByRole('button',{name:'Organizer: Connected',exact:true})).toBeVisible()
 await expect(box.locator('[data-service=cloud]')).toHaveCSS('color','rgb(63, 107, 79)')
 await expect(box.locator('[data-service=cloud] .lucide-cloud')).toHaveAttribute('fill','currentColor')
 await expect(box.locator('[data-service=cloud] .connection-status-symbol')).toHaveCount(0)
 cloudFail=true
 await page.evaluate(()=>window.dispatchEvent(new Event('focus')))
 await expect(box.getByRole('button',{name:'Cloud: Sync Failed',exact:true})).toBeVisible()
 await expect(box.locator('[data-service=cloud]')).toHaveCSS('color','rgb(151, 0, 0)')
 await expect(box.locator('[data-service=cloud] .connection-status-symbol > path')).toHaveAttribute('d','M12 4v10')
 await expect(box.getByRole('button',{name:'Network: Online',exact:true})).toBeVisible()
 await expect(box.getByRole('button',{name:'Organizer: Connected',exact:true})).toBeVisible()
 await context.setOffline(true)
 await expect(box.getByRole('button',{name:'Network: Offline',exact:true})).toBeVisible()
 await expect(box.getByRole('button',{name:'Cloud: Sync Failed',exact:true})).toBeVisible()
 cloudFail=false;organizerFail=true
 await context.setOffline(false)
 await expect(box.getByRole('button',{name:'Organizer: Sync Failed',exact:true})).toBeVisible()
 await expect(box.getByRole('button',{name:'Cloud: Up to Date',exact:true})).toBeVisible()
 organizerFail=false
 await page.evaluate(()=>window.dispatchEvent(new Event('focus')))
 await expect(box.getByRole('button',{name:'Organizer: Connected',exact:true})).toBeVisible()
 await expect(box.getByRole('button',{name:'Cloud: Up to Date',exact:true})).toBeVisible()
 await openProfile(page)
 await page.getByRole('button',{name:'Organizer & Sync',exact:true}).click()
 await page.getByText('Advanced Troubleshooting',{exact:true}).click()
 await page.getByRole('button',{name:'Disconnect Organizer',exact:true}).click();await openProfile(page)
 await expect(box.getByRole('button',{name:'Organizer: Paused',exact:true})).toBeVisible()
 await expect(box.locator('[data-service=organizer] .lucide-pause')).toHaveCount(1)
})

test('shows offline edits as pending until the durable cloud queue is confirmed synced',async({page,context})=>{
 await organizerAccount(context)
 await page.goto('/');await openProfile(page)
 await expect(page.getByRole('button',{name:'Cloud: Up to Date',exact:true})).toBeVisible()
 await expect(page.getByText('Reader prepared for offline use',{exact:false})).toBeVisible()
 await context.setOffline(true)
 await importBook(page,'Queued Offline Book');await openProfile(page)
 const cloud=page.getByRole('button',{name:'Cloud: Changes Pending',exact:true})
 await expect(cloud).toBeVisible()
 await expect(cloud).toHaveCSS('color','rgb(138, 90, 0)')
 await expect(cloud.locator('.lucide-clock')).toHaveCount(1)
 await page.keyboard.press('Escape');await account(page)
 await page.getByRole('button',{name:'Close Dialog',exact:true}).click();await openProfile(page)
 await expect(cloud).toBeVisible()
 await context.setOffline(false)
 await expect(page.getByRole('button',{name:'Cloud: Up to Date',exact:true})).toBeVisible()
})
