test('details top-edge navigation stays in the details page and restores bookshelf scroll on close', async ({ page }) => {
 await importBook(page)
 await page.getByRole('button', { name: 'Bookshelf', exact: true }).click()
 await page.evaluate(() => scrollTo(0, 500))
 const before = await page.evaluate(() => scrollY)
 await page.getByLabel('Work Actions', { exact: true }).click()
 await page.getByRole('button', { name: 'View Details', exact: true }).click()
 const details = page.getByRole('dialog', { name: 'View Details', exact: true })
 await expect(details).toBeVisible()
 const saved = await page.evaluate(() => -parseFloat(document.body.style.top))
 await details.evaluate(element => { element.scrollTop = 600 })
 await expect.poll(() => details.evaluate(element => element.scrollTop)).toBeGreaterThan(0)
 await details.getByRole('button', { name: 'Go to Details Top' }).click({ force: true })
 await expect.poll(() => details.evaluate(element => element.scrollTop)).toBe(0)
 await details.getByRole('button', { name: 'Close Dialog', exact: true }).click()
 await expect.poll(() => page.evaluate(() => scrollY)).toBe(saved)
 expect(before).toBeGreaterThan(0)
})

