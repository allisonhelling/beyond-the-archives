async function importBook(page: Page, fromNavigation = false) {
 const files = epubFiles()
 const summary = '<p>A long summary with enough lines to reach beyond the former tile preview.</p>'.repeat(18)
 files[3].content = String(files[3].content).replace('<p>Recovered summary.</p>', summary)
 files[4].content = `<html><body><h2>Chapter One</h2>${'<p>A chapter long enough to scroll without changing its identity.</p>'.repeat(80)}</body></html>`
 files[2].content = String(files[2].content).replace('</manifest>', '<item id="two" href="two.xhtml" media-type="application/xhtml+xml"/></manifest>').replace('</spine>', '<itemref idref="two"/></spine>')
 files.push({ name: 'OEBPS/two.xhtml', content: '<html><body><h2>Chapter Two</h2><p>Two.</p></body></html>' })
 const file = { name: 'mobile.epub', mimeType: 'application/epub+zip', buffer: Buffer.from(await createZip(files).arrayBuffer()) }
 if (fromNavigation) {
  const choosing = page.waitForEvent('filechooser')
  await page.getByRole('navigation', { name: 'Mobile Navigation' }).getByRole('button', { name: 'Import', exact: true }).click()
  await (await choosing).setFiles(file)
 } else await page.getByLabel('Import EPUB File').setInputFiles(file)
 await expect(page.getByLabel('Book Content')).toBeVisible()
}
async function swipe(page: Page, dx: number, dy = 0) {
 const viewport = page.getByLabel('Book Content')
 await viewport.dispatchEvent('touchstart', { touches: [{ identifier: 0, clientX: 200, clientY: 300 }] })
 await viewport.dispatchEvent('touchend', { changedTouches: [{ identifier: 0, clientX: 200 + dx, clientY: 300 + dy }] })
}
