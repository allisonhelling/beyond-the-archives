test('details top-edge scrolling does not move the chapter underneath it', async ({ page }) => {
  await importBook(page)
  await page.getByRole('button', { name: 'Contents', exact: true }).click()
  await page.getByRole('complementary', { name: 'Contents' }).getByRole('button', { name: /Chapter One/ }).click()
  const viewport = page.getByLabel('Book Content')
  await viewport.evaluate(element => { element.scrollTop = 250 })
  await expect.poll(() => viewport.evaluate(element => element.scrollTop)).toBe(250)
  await page.locator('.reading-work-name').click()
  const details = page.getByRole('dialog', { name: 'View Details' })
  await expect(details).toBeVisible()
  await details.evaluate(element => { element.scrollTop = 500 })
  await page.evaluate(() => window.dispatchEvent(new Event('scroll')))
  await details.getByRole('button', { name: 'Go to Details Top' }).click({ force: true })
  await expect.poll(() => details.evaluate(element => element.scrollTop)).toBe(0)
  expect(await viewport.evaluate(element => element.scrollTop)).toBe(250)
  await details.getByRole('button', { name: 'Close Dialog' }).click()
  expect(await viewport.evaluate(element => element.scrollTop)).toBe(250)
 })
