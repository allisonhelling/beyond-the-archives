test('persists offline reading updates and retries them once without duplicating read events', async ({ page, context }) => {
  let remote = { id: 'entry-1', version: 'v1', status: 'to_read', progress: 0, notes: '', collections: [], tags: [] }
  let reads = 0
  const requests: Record<string, unknown>[] = []
  await context.route('https://organizer.test/rest/v1/rpc/userscript_library', async route => {
    const request = route.request().postDataJSON()
    if (request.p_action === 'progress' || request.p_action === 'save') {
      requests.push(request.p_input)
      const input = request.p_input
      if (input.chapter_read && remote.progress < input.progress) reads++
      remote = { ...remote, ...input, version: `v${requests.length + 1}` }
    }
    await route.fulfill({ json: { entry: remote, collections: [] } })
  })
  await page.goto('/')
  await connectOrganizer(page)
  await page.getByLabel('Import EPUB File').setInputFiles({ name: 'sync.epub', mimeType: 'application/epub+zip', buffer: await fixture() })
  await expect(page.getByLabel('Book Content')).toBeVisible()
  await page.getByLabel('Chapter', { exact: true }).selectOption({ label: 'Chapter 1: Home' })
  await context.setOffline(true)
  await page.getByRole('button', { name: 'Mark Chapter Read', exact: true }).click()
  await expect(page.getByRole('button', { name: '✓ Chapter Read' })).toBeVisible()
  await page.reload()
  await expect(page.getByText('1 pending reading updates')).toBeVisible()
  expect(reads).toBe(0)
  await context.setOffline(false)
  await expect.poll(() => reads).toBe(1)
  await expect(page.getByText('0 pending reading updates')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'The Bookshelf' })).toBeVisible()
  expect(reads).toBe(1)
  expect(requests[0]).toMatchObject({ status: 'reading', progress: 1, chapter_read: { chapter: 1, chapter_id: '101', word_count: 1920 } })
})
