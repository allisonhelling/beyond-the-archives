import { test, expect } from '@playwright/test'
import { epubFiles } from '../../../src/test/epub-fixture'
import { createZip } from '../../../src/lib/zip'

for (const width of [390, 1280]) test(`edits progress, marks through chapters, and retains reread history at width ${width}`, async ({ page }) => {
 await page.setViewportSize({ width, height: 900 })
 const files = epubFiles()
 files[2].content = String(files[2].content).replace('</manifest>', '<item id="two" href="two.xhtml" media-type="application/xhtml+xml"/><item id="three" href="three.xhtml" media-type="application/xhtml+xml"/></manifest>').replace('</spine>', '<itemref idref="two"/><itemref idref="three"/></spine>')
 files.push({name:'OEBPS/two.xhtml',content:'<html><body><h2>Chapter 2: Away</h2><p>Second chapter.</p></body></html>'},{name:'OEBPS/three.xhtml',content:'<html><body><h2>Chapter 3: Return</h2><p>Third chapter.</p></body></html>'})
 await page.goto('/')
 await page.getByLabel('Import EPUB File').setInputFiles({name:'progress.epub',mimeType:'application/epub+zip',buffer:Buffer.from(await createZip(files).arrayBuffer())})
 await expect(page.getByLabel('Book Content')).toBeVisible()
 await page.getByRole('button',{name:'← Bookshelf',exact:true}).click()
 await page.getByRole('button',{name:'Chapter 0 of 3 — Edit Progress',exact:true}).click()
 const editor = page.getByRole('dialog',{name:'Edit Chapter Progress',exact:true})
 await expect(editor).toBeVisible()
 const bounds=(await editor.boundingBox())!
 expect(bounds.x).toBeGreaterThanOrEqual(0)
 expect(bounds.x+bounds.width).toBeLessThanOrEqual(width)
 await editor.getByLabel('Last Fully Read Chapter').fill('2')
 await editor.getByRole('button',{name:'Cancel',exact:true}).click()
 await expect(page.getByRole('button',{name:'Chapter 0 of 3 — Edit Progress',exact:true})).toBeFocused()
 await page.getByRole('button',{name:'Chapter 0 of 3 — Edit Progress',exact:true}).click()
 await editor.getByLabel('Last Fully Read Chapter').fill('4')
 await editor.getByRole('button',{name:'Save',exact:true}).click()
 await expect(editor.getByRole('alert')).toHaveText('Progress cannot exceed the known chapter count.')
 await editor.getByLabel('Last Fully Read Chapter').fill('1')
 await editor.getByRole('button',{name:'Save',exact:true}).click()
 await expect(page.getByRole('button',{name:'Chapter 1 of 3 — Edit Progress',exact:true})).toBeVisible()
 await page.reload()
 await expect(page.getByRole('button',{name:'Chapter 1 of 3 — Edit Progress',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Continue Reading →',exact:true}).click()
 await page.getByRole('button',{name:'Contents',exact:true}).click()
 await page.getByRole('complementary',{name:'Contents',exact:true}).getByRole('button',{name:'Chapter 2: Away',exact:true}).click()
 const mark = page.getByRole('button',{name:'Mark As Read',exact:true})
 await expect(mark).toHaveAttribute('title','Mark As Read Through Chapter 2')
 await mark.click()
 await expect(mark).toBeDisabled()
 await expect(page.getByRole('button',{name:'Chapter 2 of 3 — Edit Progress',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'← Bookshelf',exact:true}).click()
 await page.getByRole('button',{name:'Manage EPUB',exact:true}).click()
 await page.getByRole('button',{name:'Begin Re-Reading',exact:true}).click()
 await page.getByRole('button',{name:'Close Dialog',exact:true}).click()
 await expect(page.getByRole('button',{name:'Chapter 0 of 3 — Edit Progress',exact:true})).toBeVisible()
 await page.getByRole('button',{name:/Continue Reading|Start Reading/}).click()
 await expect(page.getByRole('button',{name:'Mark As Read',exact:true})).toHaveAttribute('title','Mark As Read Through Chapter 1')
 await page.getByRole('button',{name:'Contents',exact:true}).click()
 await page.getByRole('complementary',{name:'Contents',exact:true}).getByRole('button',{name:'Chapter 2: Away',exact:true}).click()
 await page.getByRole('button',{name:'Mark As Read',exact:true}).click()
 await expect(page.getByRole('button',{name:'Chapter 2 of 3 — Edit Progress',exact:true})).toBeVisible()
 const history = await page.evaluate(async()=>{
  const db=await new Promise<IDBDatabase>(resolve=>{const request=indexedDB.open('bta-reader');request.onsuccess=()=>resolve(request.result)})
  try{return await new Promise<{chapter:string;reread:boolean}[]>(resolve=>{const request=db.transaction('books').objectStore('books').getAll();request.onsuccess=()=>resolve(request.result[0].history)})}finally{db.close()}
 })
 expect(history).toHaveLength(3)
 expect(history.filter(event=>event.reread)).toHaveLength(2)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false)
})
