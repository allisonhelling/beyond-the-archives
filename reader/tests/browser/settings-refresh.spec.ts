test('storage keeps column widths and shows removal feedback in front of its backdrop', async ({ page }) => {
 await page.goto('/')
 await importBook(page, 'Stored Story')
 await page.getByRole('button', { name: 'Storage', exact: true }).click()
 const dialog = page.getByRole('dialog', { name: 'Manage Local Storage', exact: true })
 await expect.poll(() => page.evaluate(() => document.body.style.position)).toBe('fixed')
 const table = dialog.getByRole('table')
 await expect(table.getByRole('columnheader', { name: 'Sort By Title' })).toHaveAttribute('aria-sort', 'ascending')
 const widths = await table.getByRole('columnheader').evaluateAll(nodes => nodes.map(node => node.getBoundingClientRect().width))
 await table.getByRole('button', { name: 'Sort By Size' }).click()
 expect(await table.getByRole('columnheader').evaluateAll(nodes => nodes.map(node => node.getBoundingClientRect().width))).toEqual(widths)
 await dialog.getByRole('button', { name: 'Select All', exact: true }).click()
 page.once('dialog', confirmation => confirmation.accept())
 await dialog.getByRole('button', { name: 'Remove Download', exact: true }).click()
 await expect(dialog.getByRole('status').filter({ hasText: 'Local download removed.' })).toBeVisible()
 await dialog.getByRole('button', { name: 'Close Dialog' }).click()
 await expect.poll(() => page.evaluate(() => document.body.style.position)).toBe('')
})

test('mobile reader retains deleted work tiles and filters saved publication metadata', async ({ page }) => {
 await page.setViewportSize({width:390,height:844})
 await page.goto('/')
 await importBook(page, 'Deleted Story', undefined, 'Recovered Author', 'https://archiveofourown.org/works/8001')
 await page.evaluate(async()=>{
  const db=await new Promise<IDBDatabase>(resolve=>{const request=indexedDB.open('bta-reader');request.onsuccess=()=>resolve(request.result)})
  await new Promise<void>((resolve,reject)=>{const tx=db.transaction(['books','catalog'],'readwrite');tx.oncomplete=()=>resolve();tx.onerror=()=>reject(tx.error);for(const name of ['books','catalog']){const store=tx.objectStore(name),cursor=store.openCursor();cursor.onsuccess=()=>{const row=cursor.result;if(row){row.update({...row.value,metadata:{...row.value.metadata,publication_status:'deleted'}});row.continue()}}}})
  db.close()
 })
 await page.reload()
 await expect(page.getByRole('button',{name:'Deleted Story',exact:true})).toBeVisible()
 await expect(page.getByRole('img',{name:'Deleted',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Filters',exact:true}).click()
 await page.getByText('More Metadata Filters',{exact:true}).click()
 await page.getByRole('combobox',{name:'Publication Status',exact:true}).selectOption({label:'Deleted (1)'})
 await page.getByRole('button',{name:'Apply Filters',exact:true}).click()
 await expect(page.locator('.story-card')).toHaveCount(1)
})
