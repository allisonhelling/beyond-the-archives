import { test, expect } from '@playwright/test'
import { importBook } from './library-fixture'

for (const width of [390, 1280]) test(`restores the open EPUB, sorts by last opened, and reverses sort at ${width}px`, async ({ page }) => {
 await page.setViewportSize({ width, height: 900 })
 await page.goto('/')
 await importBook(page, 'Alpha')
 await importBook(page, 'Zebra')
 await expect(page.locator('.story-card h2')).toHaveText(['Zebra\u00a0', 'Alpha\u00a0'])
 await page.getByRole('button', { name: 'Alpha', exact: true }).click()
 await expect(page.getByLabel('Book Content')).toBeVisible()
 await page.reload()
 await expect(page.getByLabel('Book Content')).toBeVisible()
 await expect(page.locator('.reading-work-name')).toHaveText('Alpha')
 await page.getByRole('button', { name: 'Bookshelf', exact: true }).click()
 await page.reload()
 await expect(page.getByRole('heading', { name: 'The Bookshelf' })).toBeVisible()
 await expect(page.locator('.story-card h2').first()).toHaveText('Alpha\u00a0')
 await page.getByRole('button', { name: 'Sort', exact: true }).click()
 await page.getByRole('option', { name: /^Last Opened/ }).click()
 await expect(page.locator('.story-card h2').first()).toHaveText('Zebra\u00a0')
 await page.getByRole('heading', { name: 'The Bookshelf' }).click()
 await page.reload()
 await expect(page.getByRole('heading', { name: 'The Bookshelf' })).toBeVisible()
 await expect(page.getByLabel('Book Content')).toHaveCount(0)
})

