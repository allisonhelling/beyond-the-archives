import { test, expect } from '@playwright/test'
import { importBook } from './library-fixture'
test('reorders tag categories independently and keeps the choice after reload',async({page,context})=>{
 await context.route('https://beyondthearchives.vercel.app/auth/bridge',route=>route.fulfill({body:'<!doctype html>',contentType:'text/html'}))
 await page.goto('/');await importBook(page,'Ordered Tags')
 const tags=page.locator('.story-card .expandable-metadata-tags .metadata-tag')
 await expect(tags.first()).toHaveText('Recovered Tag')
 await page.getByRole('button',{name:'Profile Menu',exact:true}).click()
 await page.getByRole('button',{name:'Tag Format',exact:true}).click()
 const dialog=page.getByRole('dialog',{name:'Tag Format',exact:true})
 await dialog.getByRole('button',{name:'Move Characters Up',exact:true}).click()
 await dialog.getByRole('button',{name:'Move Characters Up',exact:true}).click()
 await expect(dialog.locator('.tag-order-list li').first()).toContainText('Characters')
 await dialog.getByRole('button',{name:'Close Dialog',exact:true}).click()
 await expect(tags.first()).toHaveText('A')
 await expect(tags.nth(1)).toHaveText('B')
 await expect(tags.nth(2)).toHaveText('Recovered Tag')
 await page.reload();await expect(tags.first()).toHaveText('A')
 await page.setViewportSize({width:390,height:844})
 await page.getByRole('button',{name:'Profile Menu',exact:true}).click()
 await page.getByRole('button',{name:'Tag Format',exact:true}).click()
 await expect(dialog.locator('.tag-order-list li').first()).toContainText('Characters')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})
