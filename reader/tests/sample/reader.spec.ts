import { readFile, writeFile } from 'node:fs/promises'
import { expect, test } from '@playwright/test'
import { importBook } from '../browser/library-fixture'

const target=new URL('../../src/sample/default-state.json',import.meta.url)
let original:string
test.beforeEach(async()=>{original=await readFile(target,'utf8')})
test.afterEach(async()=>{await writeFile(target,original)})

test('sample reader isolates account data, saves current defaults, resets and supports Sample sign-in',async({page,context,browser},testInfo)=>{
 const backendRequests:string[]=[],errors:string[]=[]
 page.on('request',request=>{if(/\/auth\/v1\/|\/rest\/v1\/|\/storage\/v1\//.test(request.url()))backendRequests.push(request.url())})
 page.on('pageerror',error=>errors.push(error.message))
 await context.addInitScript(()=>{
  if (localStorage.getItem('sample-test-initialized')) return
  localStorage.setItem('sample-test-initialized','true')
  localStorage.setItem('reader-cloud-owner','real-reader-owner')
  localStorage.setItem('reader-cloud-auth',JSON.stringify({access_token:'do-not-use',refresh_token:'do-not-use'}))
 })
 await page.goto('/')
 await expect(page.getByRole('heading',{name:'The Lantern Library'})).toBeVisible()
 await expect(page.getByRole('heading',{name:'Letters from the Observatory'})).toBeVisible()
 await expect(page.getByLabel('Local Sample Preview')).toContainText('Sample Reader')
 const lantern=page.locator('.story-card').filter({has:page.getByRole('heading',{name:'The Lantern Library'})})
 if (testInfo.project.name === 'mobile') await lantern.getByRole('button',{name:'Mark Favorite',exact:true}).click() // Existing first-tap tooltip preview.
 await lantern.getByRole('button',{name:'Mark Favorite',exact:true}).click()
 await expect(lantern.getByRole('button',{name:'Unmark Favorite',exact:true})).toBeVisible()
 await lantern.getByRole('button',{name:'The Lantern Library',exact:true}).click()
 await expect(page.getByLabel('Book Content')).toBeVisible()
 await page.getByRole('button',{name:'Mark Chapter Read',exact:true}).first().click()
 await page.getByRole('button',{name:'Bookshelf',exact:true}).click()
 await importBook(page,'Sample Imported Work')
 await expect(page.locator('.story-card')).toHaveCount(3)
 await lantern.getByRole('button',{name:'Manage EPUB',exact:true}).click()
 await page.getByLabel('Personal Notes',{exact:true}).fill('A saved sample note.')
 await page.getByRole('button',{name:'Save Personal Notes',exact:true}).click()
 await expect(page.getByText('Personal notes saved.',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Close Dialog',exact:true}).click()
 await page.getByRole('button',{name:'Toggle Dark Mode',exact:true}).click()
 await page.getByRole('button',{name:'Update Sample Data',exact:true}).click()
 await expect(page.getByRole('status').filter({hasText:'Current library saved'})).toBeVisible()
 const snapshot=JSON.parse(await readFile(target,'utf8'))
 expect(snapshot.books).toHaveLength(3)
 const saved=snapshot.books.find((entry:{state:{metadata:{title:string}}})=>entry.state.metadata.title==='The Lantern Library')
 expect(saved.state.favorite).toBe(true)
 expect(saved.state.history).toHaveLength(1)
 expect(saved.state.notes).toBe('A saved sample note.')
 expect(snapshot.preferences.dark).toBe(true)
 expect(saved.state).not.toHaveProperty('account');expect(saved.state).not.toHaveProperty('remote')
 expect(snapshot).not.toHaveProperty('connection');expect(snapshot).not.toHaveProperty('pending')
 // A fresh browser gets the project snapshot, including its imported EPUB and reading state.
 const fresh=await browser.newContext({viewport:testInfo.project.use.viewport})
 try{
  const next=await fresh.newPage();await next.goto('http://127.0.0.1:4194/')
  await expect(next.getByRole('heading',{name:'Sample Imported Work'})).toBeVisible()
  await expect(next.locator('.story-card').filter({has:next.getByRole('heading',{name:'The Lantern Library'})}).getByRole('button',{name:'Unmark Favorite',exact:true})).toBeVisible()
 }finally{await fresh.close()}
 await Promise.all([page.waitForEvent('domcontentloaded'), page.getByRole('button',{name:'Reset Sample Data',exact:true}).click()])
 await expect(page.locator('.story-card')).toHaveCount(3)
 await expect(page.getByRole('heading',{name:'Sample Imported Work'})).toBeVisible()
 await page.getByRole('button',{name:'Profile Menu',exact:true}).click()
 await page.getByRole('button',{name:'Reader Account',exact:true}).click()
 await page.getByRole('button',{name:'Log Out',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Sample Reader Sign-In'})).toBeVisible()
 await page.reload()
 await expect(page.getByRole('heading',{name:'Sample Reader Sign-In'})).toBeVisible()
 await page.getByLabel('Username or Email',{exact:true}).fill('Sample')
 await page.getByLabel('Password',{exact:true}).fill('123')
 await page.getByRole('button',{name:'Sign In',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Sample Imported Work'})).toBeVisible()
 expect(await page.evaluate(()=>localStorage.getItem('reader-cloud-owner'))).toBe('real-reader-owner')
 expect(await page.evaluate(()=>localStorage.getItem('reader-cloud-auth'))).toContain('do-not-use')
 expect(backendRequests).toEqual([])
 expect(errors).toEqual([])
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})

test('keeps failed writes and invalid snapshots from replacing defaults and supports empty saved libraries',async({page,browser})=>{
 await page.goto('/')
 await expect(page.locator('.story-card')).toHaveCount(2)
 await page.route('**/__sample-data',route=>route.fulfill({status:500,contentType:'application/json',body:'{"error":"Write failed"}'}))
 await page.getByRole('button',{name:'Update Sample Data',exact:true}).click()
 await expect(page.getByRole('alert')).toContainText('Could not save sample data')
 expect(await readFile(target,'utf8')).toBe(original)
 await page.unroute('**/__sample-data')
 const invalid=await page.evaluate(async()=>{const result=await fetch('/__sample-data',{method:'POST',headers:{'Content-Type':'application/json'},body:'{"version":99}'});return result.status})
 expect(invalid).toBe(400);expect(await readFile(target,'utf8')).toBe(original)
 await page.evaluate(async()=>{const db=await new Promise<IDBDatabase>((resolve,reject)=>{const request=indexedDB.open('bta-reader-sample:v1');request.onsuccess=()=>resolve(request.result);request.onerror=()=>reject(request.error)});await new Promise<void>((resolve,reject)=>{const tx=db.transaction(['books','catalog','contents'],'readwrite');for(const name of ['books','catalog','contents'])tx.objectStore(name).clear();tx.oncomplete=()=>resolve();tx.onerror=()=>reject(tx.error)});db.close()})
 await page.reload();await expect(page.locator('.story-card')).toHaveCount(0)
 await page.getByRole('button',{name:'Update Sample Data',exact:true}).click()
 await expect(page.getByRole('status').filter({hasText:'Current library saved'})).toBeVisible()
 const fresh=await browser.newContext()
 try{const next=await fresh.newPage();await next.goto('http://127.0.0.1:4194/');await expect(next.getByRole('heading',{name:'The Bookshelf',exact:true})).toBeVisible();await expect(next.locator('.story-card')).toHaveCount(0)}finally{await fresh.close()}
})
