import { fireEvent, render, screen, waitFor } from '@testing-library/react'
import { MemoryRouter } from 'react-router-dom'
import { beforeEach, expect, it, vi } from 'vitest'
const rpc=vi.hoisted(()=>vi.fn())
vi.mock('./import-reading-review',()=>({reviewImportReading:rpc}))
import { ImportReadingReview } from './ImportReadingReview'
const review=(id:string)=>({id,title:`Work ${id}`,source:'legacy_unknown',savedProgressKnown:false,progressKnown:true,saved:{status:'to_read',progress:0,startedAt:null,finishedAt:null},proposed:{status:'finished',progress:3,startedAt:null,finishedAt:'2026-10-20T00:00:00Z'}})
beforeEach(()=>{rpc.mockReset().mockResolvedValue({reviews:[review('a'),review('b')],total:2,changed:0,skipped:0})})
it('shows unknown progress without claiming a confirmed zero and changes nothing until explicit acceptance',async()=>{
 const changed=vi.fn(async()=>{})
 render(<MemoryRouter><ImportReadingReview onChanged={changed} /></MemoryRouter>)
 expect(screen.queryByRole('button',{name:'Review Reading Corrections'})).not.toBeInTheDocument()
 fireEvent.click(await screen.findByRole('button',{name:'Review Reading Corrections'}))
 expect(await screen.findByRole('table')).toBeVisible()
 expect(screen.getAllByText('Chapter progress unconfirmed')).toHaveLength(2)
 expect(changed).not.toHaveBeenCalled()
 fireEvent.click(screen.getByRole('checkbox',{name:'Select Correction for Work a'}))
 rpc.mockResolvedValue({reviews:[review('b')],total:1,changed:1,skipped:0})
 fireEvent.click(screen.getByRole('button',{name:'Accept Selected Corrections'}))
 await waitFor(()=>expect(rpc).toHaveBeenLastCalledWith(['a'],'accept',1))
 await waitFor(()=>expect(changed).toHaveBeenCalledTimes(1))
 expect(screen.getByText('1 corrections accepted.')).toBeVisible()
})
it('keeps all selected histories and surfaces review failures without claiming success',async()=>{
 render(<MemoryRouter><ImportReadingReview onChanged={vi.fn(async()=>{})} /></MemoryRouter>)
 fireEvent.click(await screen.findByRole('button',{name:'Review Reading Corrections'}));await screen.findByRole('table')
 fireEvent.click(screen.getByRole('button',{name:'Select All on This Page'}))
 rpc.mockRejectedValue(new Error('Connection failed'))
 fireEvent.click(screen.getByRole('button',{name:'Keep Selected Reading History'}))
 expect(await screen.findByRole('alert')).toHaveTextContent('Connection failed')
 expect(rpc).toHaveBeenLastCalledWith(['a','b'],'keep',1)
 expect(screen.getByRole('table')).toBeVisible()
})
it('toggles the review panel and refreshes pending corrections when reopened',async()=>{
 render(<MemoryRouter><ImportReadingReview onChanged={vi.fn(async()=>{})} /></MemoryRouter>)
 const toggle=await screen.findByRole('button',{name:'Review Reading Corrections'})
 expect(toggle).toHaveAttribute('aria-expanded','false')
 fireEvent.click(toggle)
 expect(await screen.findByRole('table')).toBeVisible()
 expect(toggle).toHaveAttribute('aria-expanded','true')
 fireEvent.click(toggle)
 expect(screen.queryByRole('table')).not.toBeInTheDocument()
 expect(toggle).toHaveAttribute('aria-expanded','false')
 expect(rpc).toHaveBeenCalledTimes(2)
 fireEvent.click(toggle)
 await waitFor(()=>expect(rpc).toHaveBeenCalledTimes(3))
 expect(screen.getByRole('table')).toBeVisible()
})
it('hides the action when no corrections exist and discovers new corrections after import',async()=>{
 rpc.mockResolvedValue({reviews:[],total:0,changed:0,skipped:0})
 const changed=vi.fn(async()=>{})
 const {rerender}=render(<MemoryRouter><ImportReadingReview onChanged={changed} actions={<button>Discard Scan</button>} refreshKey="before" /></MemoryRouter>)
 await waitFor(()=>expect(rpc).toHaveBeenCalledTimes(1))
 expect(screen.queryByRole('button',{name:'Review Reading Corrections'})).not.toBeInTheDocument()
 expect(screen.getByRole('button',{name:'Discard Scan'})).toBeVisible()
 rpc.mockResolvedValue({reviews:[review('a')],total:1,changed:0,skipped:0})
 rerender(<MemoryRouter><ImportReadingReview onChanged={changed} actions={<button>Discard Scan</button>} refreshKey="after" /></MemoryRouter>)
 expect(await screen.findByRole('button',{name:'Review Reading Corrections'})).toBeVisible()
})
it('hides both import entry points when the last corrections are resolved',async()=>{
 render(<MemoryRouter><ImportReadingReview onChanged={vi.fn(async()=>{})} /><ImportReadingReview onChanged={vi.fn(async()=>{})} /></MemoryRouter>)
 await waitFor(()=>expect(screen.getAllByRole('button',{name:'Review Reading Corrections'})).toHaveLength(2))
 fireEvent.click(screen.getAllByRole('button',{name:'Review Reading Corrections'})[0])
 await screen.findByRole('table')
 fireEvent.click(screen.getByRole('button',{name:'Select All on This Page'}))
 rpc.mockResolvedValue({reviews:[],total:0,changed:2,skipped:0})
 fireEvent.click(screen.getByRole('button',{name:'Accept Selected Corrections'}))
 await waitFor(()=>expect(screen.queryByRole('button',{name:'Review Reading Corrections'})).not.toBeInTheDocument())
 expect(screen.queryByRole('table')).not.toBeInTheDocument()
 expect(screen.getByRole('status')).toHaveTextContent('2 corrections accepted.')
})
