import { expect, test } from '@playwright/test'
import { fixture, login } from './library-fixture'

test('author pages automatically group saved fics and reuse library filters, pagination, and detail navigation', async ({ page }) => {
 test.setTimeout(60000) // Pagination, detail return, filtering, and multiple reloads.
 const tables = await fixture(page)
 const author = 'A Writer / 雨 & Co'
 for (let i = 0; i < 29; i++) {
  const authors = i === 28 ? ['A Writer'] : i === 0 ? [author, 'Coauthor'] : [author]
  tables.works.push({ id: `author-work-${i}`, ao3_work_id: 8000 + i, title: `Saved Fic ${String(i).padStart(2, '0')}`, published_chapters: 3, total_chapters: 3, is_complete: true })
  tables.library_entries.push({ id: `author-entry-${i}`, work_id: `author-work-${i}`, original_url: `https://archiveofourown.org/works/${8000 + i}`, reading_status: i % 2 ? 'finished' : 'to_read', last_read_chapter: i % 2 ? 3 : 0, notes: '', personal_rating: null, is_favorite: i === 0, created_at: '2026-10-25T12:00:00Z', metadata_overrides: { authors, author_links: { [author]: 'https://archiveofourown.org/users/Writer' }, fandoms: ['Saved Fandom'] } })
 }
 await page.goto('/stories/author-entry-0'); await login(page)
 const byline = page.locator('.story-details-authors')
 await expect(byline.getByRole('link', { name: author, exact: true })).toHaveAttribute('href', 'https://archiveofourown.org/users/Writer')
 await expect(byline.getByRole('link', { name: author, exact: true })).toHaveAttribute('target', '_blank')
 await expect(byline.getByRole('link', { name: 'Coauthor', exact: true })).toHaveCount(0)
 await page.goto('/library')
 const tileAuthor = page.locator('.story-card .authors').getByRole('link', { name: author, exact: true }).first()
 await expect(tileAuthor).toHaveAttribute('href', `/authors/${encodeURIComponent(author)}`)
 await tileAuthor.click()
 await expect(page.getByRole('heading', { level: 1, name: author, exact: true })).toBeVisible()
 await expect(page.getByText('28 fics saved in your library')).toBeVisible()
 await page.getByRole('combobox', { name: 'Works per Page', exact: true }).first().selectOption('25')
 await expect(page.locator('.story-card')).toHaveCount(25)
 await expect(page.getByRole('button', { name: 'Show Series', exact: true })).toHaveCount(0)
 await expect(page.getByRole('heading', { name: 'Saved Fic 28', exact: true })).toHaveCount(0)
 await page.getByRole('button', { name: 'Next', exact: true }).first().click()
 await expect(page.locator('.story-card')).toHaveCount(3)
 const title = page.locator('.story-card-title h2 a').first()
 const savedTitle = await title.textContent()
 await title.click()
 await expect(page.getByRole('heading', { level: 1, name: savedTitle!, exact: true })).toBeVisible()
 await page.getByRole('link', { name: /Back to/ }).click()
 await expect(page.locator('.story-card')).toHaveCount(3)
 await page.goto(page.url() + '&size=25')
 await expect(page.locator('.story-card')).toHaveCount(3)
 await page.reload()
 await expect(page.locator('.story-card')).toHaveCount(3)
 await page.getByRole('button', { name: 'Filters', exact: true }).click()
 await expect(page.getByRole('button', { name: 'Save as Author Default', exact: true })).toBeVisible()
 await page.getByRole('button', { name: 'Favorites', exact: true }).click()
 await expect(page.locator('.story-card')).toHaveCount(3)
 await page.getByRole('button', { name: 'Apply Filters', exact: true }).click()
 await expect(page.locator('.story-card')).toHaveCount(1)
 await expect(page.getByRole('heading', { name: 'Saved Fic 00', exact: true })).toBeVisible()
 await page.getByRole('button', { name: 'Clear All Filters', exact: true }).first().click()
 await expect(page.locator('.story-card')).toHaveCount(25)
 await page.getByRole('region', { name: 'Library Toolbar', exact: true }).getByRole('button', { name: 'Hide', exact: true }).click()
 await page.evaluate(() => window.scrollTo(0, 0))
 expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
 await page.screenshot({ path: `test-results/author-page-${page.viewportSize()!.width}.png` })
 await page.goto('/authors/Coauthor')
 await expect(page.locator('.story-card')).toHaveCount(1)
 await expect(page.getByText('1 fic saved in your library')).toBeVisible()
 await page.goto('/authors/Unknown')
 await expect(page.locator('.story-card')).toHaveCount(0)
 await expect(page.getByRole('heading', { name: 'No Stories Here Yet' })).toBeVisible()
})
