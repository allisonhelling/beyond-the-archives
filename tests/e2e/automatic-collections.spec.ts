import { automaticCollectionRules } from '../../src/features/library/collections/automatic-collections'
import { defaultReadingFilters } from '../../src/features/library/reading-search'
import { expect, test } from '@playwright/test'
import { fixture, login } from './library-fixture'

test('automatic collection rules persist and update connected library results, counts and manual pickers', async ({ page }) => {
 const tables = await fixture(page)
 for (const [id, fandom, tag] of [[101,'Fandom','Found Family'],[102,'Other fandom','Found Family'],[103,'Fandom','Angst']] as const) {
  tables.works.push({id:`work-${id}`,ao3_work_id:id,verified_chapters:{}})
  tables.library_entries.push({id:`entry-${id}`,work_id:`work-${id}`,original_url:`https://archiveofourown.org/works/${id}`,reading_status:'to_read',last_read_chapter:0,notes:'',is_favorite:false,metadata_overrides:{title:`Work ${id}`,authors:[`Writer ${id}`],fandoms:[fandom],additional_tags:[tag]},created_at:'2026-10-21T00:00:00Z'})
 }
 await page.goto('/library'); await login(page)
 await page.getByRole('button',{name:'Edit Collections',exact:true}).click()
 const shelf = page.getByRole('navigation',{name:'Library shelves',exact:true})
 await shelf.getByRole('button',{name:'New collection',exact:true}).last().click()
 let dialog=page.getByRole('dialog',{name:'New collection',exact:true})
 await dialog.getByRole('textbox',{name:'Name',exact:true}).fill('Found family fandom')
 await dialog.getByRole('checkbox',{name:'Automatic collection',exact:true}).check()
 for (const name of ['Favorites', 'In a Series']) {
  const toggle = dialog.getByRole('button', { name, exact: true })
  const before = await toggle.boundingBox()
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  const after = await toggle.boundingBox()
  expect(after?.width).toBe(before?.width)
  expect(after?.height).toBe(before?.height)
  await expect(dialog.getByLabel('Active filters')).toContainText(name === 'Favorites' ? 'Favorites Only' : 'In a Series Only')
  await toggle.click()
 }
 await dialog.getByRole('button',{name:/Select fandoms/}).click()
 await dialog.getByRole('checkbox',{name:/^Fandom/}).check()
 await dialog.getByRole('textbox',{name:'Name',exact:true}).click()
 const tags=dialog.getByRole('searchbox',{name:'Tags',exact:true})
 await tags.fill('Found Family'); await tags.press('Enter')
 await dialog.getByRole('heading',{name:'New collection',exact:true}).click()
 await dialog.getByRole('button',{name:'Create collection',exact:true}).click()
 await expect(dialog).toHaveCount(0)
 const spine=shelf.getByRole('button',{name:'Found family fandom',exact:true})
 await expect(spine).toHaveAttribute('data-spine-design','lunar-phases')
 await expect(spine.locator('.collection-spine-count')).toHaveText('1')
 const collection=tables.collections.find(item=>item.name==='Found family fandom')!
 expect(collection.automatic_rules).toMatchObject({filters:{fandoms:['Fandom'],tags:'Found Family'}})
 await page.goto(`/library?shelf=${collection.id}`)
 await expect(page.locator('.work-card')).toHaveCount(1)
 await expect(page.getByRole('heading',{name:'Work 101',exact:true})).toBeVisible()
 expect(tables.collection_works).toHaveLength(0)
 await page.locator('.work-card h2 a').click()
 const organization=page.getByRole('region',{name:'Reading and organization',exact:true})
 await expect(organization.getByText('Found family fandom',{exact:true})).toBeVisible()
 await organization.getByRole('button',{name:'Edit Collections',exact:true}).click()
 dialog=page.getByRole('dialog',{name:'Edit Collections',exact:true})
 await expect(dialog.getByRole('checkbox',{name:'Found family fandom',exact:true})).toHaveCount(0)
 await dialog.getByRole('button',{name:'Cancel',exact:true}).click()
 // A later metadata retrieval makes another saved work eligible.
 Object.assign(tables.library_entries.find(item=>item.id==='entry-103')!,{metadata_overrides:{title:'Work 103',authors:['Writer 103'],fandoms:['Fandom'],additional_tags:['Found Family']}})
 await page.goto(`/library?shelf=${collection.id}`)
 await expect(page.locator('.work-card')).toHaveCount(2)
 await page.reload()
 await expect(page.locator('.work-card')).toHaveCount(2)
 await page.getByRole('button',{name:'Edit Collections',exact:true}).click()
 await shelf.getByRole('button',{name:'Found family fandom',exact:true}).click()
 dialog=page.getByRole('dialog',{name:'Edit collection',exact:true})
 await dialog.getByRole('searchbox',{name:'Search author',exact:true}).fill('Writer 103')
 await dialog.getByRole('heading',{name:'Edit collection',exact:true}).click()
 await dialog.getByRole('button',{name:'Save changes',exact:true}).click()
 await expect(dialog).toHaveCount(0)
 await expect(page.locator('.work-card')).toHaveCount(1)
 await expect(page.getByRole('heading',{name:'Work 103',exact:true})).toBeVisible()
 expect(tables.collection_works).toHaveLength(0)
})

test('existing manual collections can become automatic without replacing their identity or appearance', async ({ page }, info) => {
 const tables=await fixture(page)
 tables.collections.push({id:'convert-collection',name:'Converted reads',description:'Keep my summary',color:'#123456',symbol:'moon',default_key:null,sort_position:0})
 for (const [id,title] of [[501,'Eligible fic'],[502,'Manual-only fic']] as const) {
  tables.works.push({id:`work-${id}`,ao3_work_id:id,verified_chapters:{}})
  tables.library_entries.push({id:`entry-${id}`,work_id:`work-${id}`,original_url:`https://archiveofourown.org/works/${id}`,reading_status:'to_read',last_read_chapter:0,notes:'Keep fic notes',is_favorite:false,metadata_overrides:{title,authors:[id===501?'Eligible author':'Another author'],fandoms:[]},created_at:'2026-10-21T00:00:00Z'})
 }
 tables.collection_works.push({collection_id:'convert-collection',library_entry_id:'entry-502'})
 await page.goto('/library?shelf=convert-collection'); await login(page)
 await expect(page.getByRole('heading',{name:'Manual-only fic',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Edit Collections',exact:true}).click()
 await page.getByRole('navigation',{name:'Library shelves',exact:true}).getByRole('button',{name:'Converted reads',exact:true}).click()
 const dialog=page.getByRole('dialog',{name:'Edit collection',exact:true})
 const automatic=dialog.getByRole('checkbox',{name:'Automatic collection',exact:true})
 await expect(automatic).toBeEnabled()
 await automatic.check()
 await expect(dialog.getByRole('group',{name:'Collection Filters',exact:true})).toBeVisible()
 await expect(dialog.getByRole('searchbox',{name:'Search title or author',exact:true})).toHaveCount(0)
 const layout=await dialog.evaluate(element=>{
  const box=(selector:string)=>element.querySelector(selector)!.getBoundingClientRect().toJSON()
  return {rules:box('.collection-rule-filters'),preview:box('.collection-preview'),dates:box('.updated-filter'),toggles:box('.filter-membership-toggles'),input:box('.date-filter-input'),overflow:element.scrollWidth>element.clientWidth}
 })
 expect(layout.overflow).toBe(false)
 if(info.project.name==='mobile') {
  expect(layout.rules.bottom).toBeLessThanOrEqual(layout.preview.top)
  expect(layout.toggles.bottom).toBeLessThanOrEqual(layout.dates.top)
  await expect(dialog.getByRole('radio',{name:'Forest',exact:true})).toHaveCount(0)
  const chooseColor=dialog.getByRole('button',{name:'Choose Color',exact:true})
  await chooseColor.click()
  await expect(chooseColor).toHaveAttribute('aria-expanded','true')
  await dialog.getByRole('radio',{name:'Forest',exact:true}).check()
  await dialog.getByRole('button',{name:'Custom color',exact:true}).click()
  await dialog.getByRole('textbox',{name:'Custom color (hex)',exact:true}).fill('#123456')
  await dialog.getByRole('button',{name:'Custom color',exact:true}).click()
  await chooseColor.click()
  await expect(dialog.getByRole('radio',{name:'Forest',exact:true})).toHaveCount(0)
  const chooseSymbol=dialog.getByRole('button',{name:'Choose Symbol',exact:true})
  await chooseSymbol.click()
  await dialog.getByRole('radio',{name:'Moon',exact:true}).check()
  await dialog.getByRole('radio',{name:'Moon',exact:true}).press('Escape')
  await expect(chooseSymbol).toHaveAttribute('aria-expanded','false')
  await expect(dialog).toBeVisible()
 } else {
  expect(layout.toggles.left).toBeGreaterThanOrEqual(layout.dates.right)
  expect(layout.toggles.top).toBeLessThan(layout.dates.bottom)
  expect(layout.input.width).toBeLessThan(160)
  await expect(dialog.getByRole('button',{name:'Choose Color',exact:true})).toBeHidden()
 }
 await dialog.getByRole('searchbox',{name:'Search author',exact:true}).fill('Eligible')
 await dialog.getByRole('heading',{name:'Edit collection',exact:true}).click()
 await dialog.screenshot({path:`test-results/convert-collection-${info.project.name}.png`})
 await dialog.getByRole('button',{name:'Save changes',exact:true}).click()
 await expect(dialog).toHaveCount(0)
 await expect(page.getByRole('heading',{name:'Eligible fic',exact:true})).toBeVisible()
 await expect(page.getByRole('heading',{name:'Manual-only fic',exact:true})).toHaveCount(0)
 expect(tables.collections).toHaveLength(1)
 expect(tables.collections[0]).toMatchObject({id:'convert-collection',name:'Converted reads',description:'Keep my summary',color:'#123456',symbol:'moon',automatic_rules:{filters:{query:'Eligible'}}})
 expect(tables.collection_works).toHaveLength(0)
 expect(tables.library_entries).toHaveLength(2)
 expect(tables.library_entries.every(entry=>entry.notes==='Keep fic notes')).toBe(true)
 await page.reload()
 await expect(page.getByRole('heading',{name:'Eligible fic',exact:true})).toBeVisible()
})

test('turning automation off keeps current works, removes filter tags, and stops future additions', async ({ page }) => {
 const tables=await fixture(page)
 tables.collections.push({id:'automatic-stop',name:'Batman reads',description:'My summary',default_key:null,automatic_rules:automaticCollectionRules({...defaultReadingFilters,query:'Writer'})})
 for (const [id,author] of [[801,'Writer'],[802,'Other author']] as const) {
  tables.works.push({id:`work-${id}`,ao3_work_id:id,verified_chapters:{}})
  tables.library_entries.push({id:`entry-${id}`,work_id:`work-${id}`,original_url:`https://archiveofourown.org/works/${id}`,reading_status:'to_read',last_read_chapter:0,notes:'',is_favorite:false,metadata_overrides:{title:`Work ${id}`,authors:[author]},created_at:'2026-10-21T00:00:00Z'})
 }
 await page.goto('/library?shelf=automatic-stop'); await login(page)
 await expect(page.locator('.work-card')).toHaveCount(1)
 await expect(page.getByRole('list',{name:'Automatic Collection Filters',exact:true})).toHaveText('Author: Writer')
 const edit=async()=>{
  await page.getByRole('button',{name:'Edit Collections',exact:true}).click()
  await page.getByRole('navigation',{name:'Library shelves',exact:true}).getByRole('button',{name:'Batman reads',exact:true}).click()
  return page.getByRole('dialog',{name:'Edit collection',exact:true})
 }
 let dialog=await edit()
 await dialog.getByRole('checkbox',{name:'Automatic collection',exact:true}).click()
 let warning=page.getByRole('dialog',{name:'Turn Off Automatic Collection?',exact:true})
 await warning.getByRole('button',{name:'Cancel',exact:true}).click()
 await expect(dialog.getByRole('checkbox',{name:'Automatic collection',exact:true})).toBeChecked()
 await dialog.getByRole('checkbox',{name:'Automatic collection',exact:true}).click()
 warning=page.getByRole('dialog',{name:'Turn Off Automatic Collection?',exact:true})
 await warning.getByRole('button',{name:'Keep Works and Turn Off',exact:true}).click()
 expect(tables.collections[0].automatic_rules).not.toBeNull()
 await dialog.getByRole('button',{name:'Save changes',exact:true}).click()
 await expect(dialog).toHaveCount(0)
 await expect(page.locator('.work-card')).toHaveCount(1)
 await expect(page.getByRole('list',{name:'Automatic Collection Filters',exact:true})).toHaveCount(0)
 expect(tables.collection_works).toEqual([{collection_id:'automatic-stop',library_entry_id:'entry-801'}])
 expect(tables.collections[0].automatic_rules).toBeNull()
 Object.assign(tables.library_entries[1],{metadata_overrides:{title:'Work 802',authors:['Writer']}})
 await page.reload()
 await expect(page.locator('.work-card')).toHaveCount(1)
 await expect(page.getByRole('heading',{name:'Work 801',exact:true})).toBeVisible()
 dialog=await edit()
 await expect(dialog.getByRole('group',{name:'Collection Filters',exact:true})).toHaveCount(0)
})

test('four-pointed star and two-line scroll symbols save and appear on collection spines', async ({page})=>{
 const tables=await fixture(page)
 await page.goto('/library'); await login(page)
 await page.getByRole('button',{name:'Edit Collections',exact:true}).click()
 const shelf=page.getByRole('navigation',{name:'Library shelves',exact:true})
 for (const [label,symbol] of [['Four-pointed Star','sparkle'],['Scroll With Text','scroll']]) {
  await shelf.getByRole('button',{name:'New collection',exact:true}).last().click()
  const dialog=page.getByRole('dialog',{name:'New collection',exact:true})
  await dialog.getByRole('textbox',{name:'Name',exact:true}).fill(label)
  const choose=dialog.getByRole('button',{name:'Choose Symbol',exact:true})
  if(await choose.isVisible()) await choose.click()
  await dialog.getByRole('radio',{name:label,exact:true}).check()
  await dialog.getByRole('button',{name:'Create collection',exact:true}).click()
  await expect(dialog).toHaveCount(0)
  expect(tables.collections.find(collection=>collection.name===label)?.symbol).toBe(symbol)
  await expect(shelf.getByRole('button',{name:label,exact:true}).locator(`.lucide-${symbol==='sparkle'?'sparkle':'scroll-text'}`)).toBeVisible()
 }
})
