const editor = (page: Page, title: string) => page.getByRole('region', { name: `${title} Editor`, exact: true })
const field = (scope: Locator, group: string, key: string) => scope.locator(`[data-display-group="${group}"][data-display-field="${key}"]`).last()
const stored = (page: Page) => page.evaluate(() => localStorage.getItem('between-chapters:display:v1'))
async function manage(scope: Locator, open: boolean) {
  const button = scope.getByRole('button', { name: 'Hide/Show Information', exact: true })
  if (await button.getAttribute('aria-expanded') !== String(open)) await button.click()
}

async function dragInformation(page: Page, source: Locator, destination: Locator, mobile: boolean) {
  // Wrapped inline fields can have an empty center in their overall bounding box.
  const firstRect = (element: Element) => element.getClientRects()[0].toJSON() as { x: number; y: number; width: number; height: number }
  const from = await source.evaluate(firstRect), to = await destination.evaluate(firstRect)
  let projected: {x:number;y:number;width:number;height:number} | null = null
  const start = { x: from.x + from.width / 2, y: from.y + from.height / 2 }, end = { x: to.x + to.width / 2, y: to.y + to.height / 2 }
  if (mobile) {
    const session = await page.context().newCDPSession(page)
    await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [start] })
    for (let step = 1; step <= 8; step++) await session.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: start.x + (end.x - start.x) * step / 8, y: start.y + (end.y - start.y) * step / 8 }] })
    await expect(page.locator('.display-drop-shadow').first()).toBeVisible(); expect(await page.evaluate(() => window.getSelection()?.toString() ?? '')).toBe('')
    projected = await page.locator('.display-drop-shadow').first().boundingBox()
    await session.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await session.detach()
  } else {
    await page.mouse.move(start.x, start.y); await page.mouse.down(); await page.mouse.move(end.x, end.y, { steps: 8 }); await expect(page.locator('.display-drop-shadow').first()).toBeVisible(); expect(await page.evaluate(() => window.getSelection()?.toString() ?? '')).toBe(''); projected = await page.locator('.display-drop-shadow').first().boundingBox(); await page.mouse.up()
  }
  const placed = await source.evaluate(node => node.closest('[data-display-field]')!.getBoundingClientRect().toJSON())
  expect(placed.y).toBeCloseTo(projected!.y, 0)
}

