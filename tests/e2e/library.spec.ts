async function closeAppearance(dialog: Locator) {
  for (const kind of ['Color', 'Symbol']) {
    const button=dialog.getByRole('button',{name:`Choose ${kind}`,exact:true})
    if(await button.isVisible() && await button.getAttribute('aria-expanded')==='true') await button.click()
  }
}
async function openAppearance(dialog: Locator, kind: 'Color' | 'Symbol') {
  const button = dialog.getByRole('button', { name: `Choose ${kind}`, exact: true })
  if (!await button.isVisible()) return
  const other = dialog.getByRole('button', { name: `Choose ${kind === 'Color' ? 'Symbol' : 'Color'}`, exact: true })
  if (await other.getAttribute('aria-expanded') === 'true') await other.click()
  if (await button.getAttribute('aria-expanded') !== 'true') await button.click()
}
async function library(page: Page, mobile: boolean) { await page.getByRole('navigation', { name: mobile ? 'Mobile Navigation' : 'Main Navigation' }).getByRole('link', { name: 'Library', exact: true }).click() }
