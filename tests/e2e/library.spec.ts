test('Shift-drag selects a range and selected collections move together without changing their order', async ({ page }) => {
  const tables = await fixture(page)
  tables.collections = ['Alpha', 'Beta', 'Gamma', 'Delta', 'Epsilon'].map((name, index) => ({ id: `group-${index}`, name, default_key: null }))
  await page.goto('/library'); await login(page)
  await page.getByRole('button', { name: 'Edit Collections', exact: true }).click()
  const shelf = page.getByRole('navigation', { name: 'Library shelves', exact: true })
  const book = (name: string) => shelf.getByRole('button', { name, exact: true })
  const titles = shelf.locator('.collection-spine-editor .collection-spine-title')
  const help = page.locator('.collection-selection-trigger button[aria-label="Collection controls"]')
  if (page.viewportSize()!.width <= 650) await expect(help).toBeHidden()
  else {
    await help.focus()
    await expect(page.getByRole('tooltip')).toContainText('Shift + click or drag: select a range.')
    await expect(page.getByRole('tooltip')).toContainText('Drag a selected book: move the selected group.')
    await page.keyboard.press('Escape')
    await expect(page.getByRole('tooltip')).toHaveCount(0)
  }
  await book('Beta').evaluate(element => element.scrollIntoView({ block: 'center' }))
  const source = (await book('Beta').boundingBox())!, end = (await book('Delta').boundingBox())!
  await page.keyboard.down('Shift')
  await page.mouse.move(source.x + source.width / 2, source.y + source.height / 2)
  await page.mouse.down()
  await page.mouse.move(end.x + end.width / 2, end.y + end.height / 2, { steps: 15 })
  await expect(page.getByText('3 selected', { exact: true })).toBeVisible()
  await expect(shelf.locator('[data-dragging="true"]')).toHaveCount(0)
  await page.mouse.up()
  await page.keyboard.up('Shift')
  await expect(page.getByRole('button', { name: 'Cancel selection', exact: true })).toBeVisible()
  await expect(titles).toHaveText(['Alpha', 'Beta', 'Gamma', 'Delta', 'Epsilon'])
  for (const name of ['Beta', 'Gamma', 'Delta']) await expect(book(name)).toHaveAttribute('aria-pressed', 'true')
  const count = page.getByText('3 selected', { exact: true })
  if (page.viewportSize()!.width <= 650) await expect(help).toBeHidden()
  else await expect(count.locator('..').getByRole('button', { name: 'Collection controls', exact: true })).toBeVisible()
  async function shiftDrag(fromName: string, toName: string, expected: number, cancel = false) {
    await book(fromName).evaluate(element => element.scrollIntoView({ block: 'center' }))
    const start = (await book(fromName).boundingBox())!, end = (await book(toName).boundingBox())!
    await page.keyboard.down('Shift')
    await page.mouse.move(start.x + start.width / 2, start.y + start.height / 2)
    await page.mouse.down()
    await page.mouse.move(end.x + end.width / 2, end.y + end.height / 2, { steps: 10 })
    await expect(page.getByText(`${expected} selected`, { exact: true })).toBeVisible()
    if (cancel) await page.keyboard.press('Escape')
    await page.mouse.up()
    await page.keyboard.up('Shift')
  }
  await shiftDrag('Beta', 'Gamma', 1, true)
  await expect(count).toBeVisible()
  await shiftDrag('Beta', 'Gamma', 1)
  await expect(book('Beta')).toHaveAttribute('aria-pressed', 'false')
  await expect(book('Gamma')).toHaveAttribute('aria-pressed', 'false')
  await expect(book('Delta')).toHaveAttribute('aria-pressed', 'true')
  await shiftDrag('Beta', 'Gamma', 3)
  await book('Beta').evaluate(element => element.scrollIntoView({ block: 'center' }))
  const from = (await book('Beta').boundingBox())!, to = (await book('Alpha').boundingBox())!
  await page.mouse.move(from.x + from.width / 2, from.y + from.height / 2)
  await page.mouse.down()
  await page.mouse.move(to.x + to.width / 2, to.y + to.height / 2, { steps: 10 })
  await expect(shelf.locator('[data-dragging="true"]')).toHaveCount(3)
  await page.mouse.up()
  await expect(titles).toHaveText(['Beta', 'Gamma', 'Delta', 'Alpha', 'Epsilon'])
  await expect(page.getByText('3 selected', { exact: true })).toBeVisible()
  await book('Delta').press('Alt+ArrowRight')
  await expect(titles).toHaveText(['Alpha', 'Beta', 'Gamma', 'Delta', 'Epsilon'])
  await book('Delta').press('Alt+ArrowRight')
  await expect(titles).toHaveText(['Alpha', 'Epsilon', 'Beta', 'Gamma', 'Delta'])
  await expect(book('Delta')).toBeFocused()
  await page.keyboard.press('Alt+ArrowRight')
  await expect(titles).toHaveText(['Alpha', 'Epsilon', 'Beta', 'Gamma', 'Delta'])
  await page.keyboard.press('Alt+ArrowLeft')
  await expect(titles).toHaveText(['Alpha', 'Beta', 'Gamma', 'Delta', 'Epsilon'])
  await expect(book('Delta')).toBeFocused()
  await page.keyboard.press('Alt+ArrowLeft')
  await expect(titles).toHaveText(['Beta', 'Gamma', 'Delta', 'Alpha', 'Epsilon'])
  await page.keyboard.press('Alt+ArrowLeft')
  await expect(titles).toHaveText(['Beta', 'Gamma', 'Delta', 'Alpha', 'Epsilon'])
  await page.keyboard.press('Alt+ArrowRight')
  await expect(titles).toHaveText(['Alpha', 'Beta', 'Gamma', 'Delta', 'Epsilon'])
  await expect(book('Delta')).toBeFocused()
  await page.keyboard.press('Alt+ArrowRight')
  await expect(titles).toHaveText(['Alpha', 'Epsilon', 'Beta', 'Gamma', 'Delta'])
  await page.reload()
  await page.getByRole('button', { name: 'Edit Collections', exact: true }).click()
  await expect(titles).toHaveText(['Alpha', 'Epsilon', 'Beta', 'Gamma', 'Delta'])
  await book('Beta').evaluate(element => element.scrollIntoView({ block: 'center' }))
  const cancelSource = (await book('Beta').boundingBox())!, cancelEnd = (await book('Gamma').boundingBox())!
  await page.keyboard.down('Shift')
  await page.mouse.move(cancelSource.x + cancelSource.width / 2, cancelSource.y + cancelSource.height / 2)
  await page.mouse.down()
  await page.mouse.move(cancelEnd.x + cancelEnd.width / 2, cancelEnd.y + cancelEnd.height / 2, { steps: 10 })
  await expect(page.getByText('2 selected', { exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.mouse.up()
  await page.keyboard.up('Shift')
  await expect(page.getByText('0 selected', { exact: true })).toBeVisible()
  await expect(titles).toHaveText(['Alpha', 'Epsilon', 'Beta', 'Gamma', 'Delta'])
  await book('Beta').click()
  await book('Delta').click()
  await expect(page.getByText('2 selected', { exact: true })).toBeVisible()
  await book('Beta').press('Alt+ArrowRight')
  await expect(titles).toHaveText(['Alpha', 'Epsilon', 'Beta', 'Gamma', 'Delta'])
  await page.keyboard.press('Alt+ArrowLeft')
  await expect(titles).toHaveText(['Alpha', 'Beta', 'Delta', 'Epsilon', 'Gamma'])
  await expect(book('Beta')).toBeFocused()
  await page.keyboard.press('Alt+ArrowRight')
  await expect(titles).toHaveText(['Alpha', 'Epsilon', 'Beta', 'Delta', 'Gamma'])
  await expect(book('Beta')).toBeFocused()
  await expect(page.getByText('2 selected', { exact: true })).toBeVisible()
  await expect(page.getByRole('dialog')).toHaveCount(0)
})
