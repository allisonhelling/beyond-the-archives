import { expect, test } from '@playwright/test'
import { fixture, login } from './library-fixture'

test('rereading resets progress while preserving history and private fields', async ({ page }) => {
 const tables=await fixture(page)
 tables.works.push({id:'reread-work',ao3_work_id:88001,verified_chapters:{}})
 tables.library_entries.push({id:'reread-entry',work_id:'reread-work',original_url:'https://archiveofourown.org/works/88001',reading_status:'finished',last_read_chapter:2,notes:'Keep my notes',is_favorite:true,personal_rating:4,finished_at:'2026-10-01T00:00:00Z',reading_history:[{action:'chapter_read',id:'first-read',chapter:1,chapter_id:null,word_count:1000,is_reread:false,status:'reading',at:'2026-09-30T00:00:00Z'}],metadata_overrides:{title:'Reread Story',authors:[],fandoms:[],published_chapters:2,total_chapters:2,publication_status:'complete'}})
 await page.goto('/library');await login(page)
 await page.getByRole('button',{name:'Begin Re-Reading',exact:true}).click()
 await expect.poll(()=>tables.library_entries[0].reading_status).toBe('re_reading')
 expect(tables.library_entries[0]).toMatchObject({last_read_chapter:0,notes:'Keep my notes',is_favorite:true,personal_rating:4,finished_at:null})
 expect((tables.library_entries[0].reading_history as {action:string}[]).filter(event=>event.action==='chapter_read')).toHaveLength(1)
 await page.reload()
 await expect(page.getByRole('img',{name:'Re-Reading',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Chapter 0 of 2 — Edit Progress',exact:true}).click()
 const progress=page.getByRole('dialog',{name:'Edit Chapter Progress',exact:true})
 await progress.getByRole('spinbutton').fill('1');await progress.getByRole('button',{name:'Save',exact:true}).click()
 await expect.poll(()=>tables.library_entries[0].last_read_chapter).toBe(1)
 expect(tables.library_entries[0].reading_status).toBe('re_reading')
 await page.getByRole('link',{name:'Reread Story',exact:true}).click()
 await page.getByRole('combobox',{name:'Reading Status for Reread Story',exact:true}).selectOption('finished')
 await page.getByRole('combobox',{name:'Reading Status for Reread Story',exact:true}).selectOption('re_reading')
 await expect.poll(()=>tables.library_entries[0].last_read_chapter).toBe(0)
 expect(tables.library_entries[0].reading_status).toBe('re_reading')
})

test('custom collection removal preserves the work and menu actions follow reading status',async({page})=>{
 const tables=await fixture(page)
 tables.collections.push({id:'custom-one',name:'First Collection',default_key:null,automatic_rules:null,color:'#970000',symbol:'book',created_at:'2026-01-01T00:00:00Z'})
 tables.collections.push({id:'custom-two',name:'Second Collection',default_key:null,automatic_rules:null,color:'#970000',symbol:'book',created_at:'2026-01-01T00:00:00Z'})
 tables.works.push({id:'menu-rules-work',ao3_work_id:88002,verified_chapters:{}})
 tables.library_entries.push({id:'menu-rules-entry',work_id:'menu-rules-work',original_url:'https://archiveofourown.org/works/88002',reading_status:'to_read',last_read_chapter:0,notes:'Keep notes',is_favorite:false,personal_rating:null,metadata_overrides:{title:'Menu Rules',authors:[],fandoms:[]}})
 tables.collection_works.push({collection_id:'custom-one',library_entry_id:'menu-rules-entry'},{collection_id:'custom-two',library_entry_id:'menu-rules-entry'})
 await page.goto('/library?shelf=custom-one');await login(page)
 await page.getByLabel('Story Actions for Menu Rules').click()
 await expect(page.getByRole('link',{name:'Open in Wayback',exact:true})).toBeVisible()
 await expect(page.getByRole('button',{name:'Mark as Finished',exact:true})).toHaveCount(0)
 await expect(page.getByRole('button',{name:'Mark as Paused Reading',exact:true})).toHaveCount(0)
 await expect(page.getByRole('button',{name:'Change Status to On Hiatus',exact:true})).toBeVisible()
 await expect(page.getByRole('button',{name:'Change Status to Abandoned',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Change Status to On Hiatus',exact:true}).click()
 await expect.poll(()=>(tables.library_entries[0].metadata_overrides as {publication_status:string}).publication_status).toBe('hiatus')
 await page.getByLabel('Story Actions for Menu Rules').click()
 await page.getByRole('button',{name:'Change Status to Abandoned',exact:true}).click()
 await expect.poll(()=>(tables.library_entries[0].metadata_overrides as {publication_status:string}).publication_status).toBe('abandoned')
 await page.getByLabel('Story Actions for Menu Rules').click()
 await page.getByRole('button',{name:'Remove from Collection',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Menu Rules',exact:true})).toHaveCount(0)
 expect(tables.library_entries).toHaveLength(1)
 expect(tables.library_entries[0].notes).toBe('Keep notes')
 expect(tables.collection_works).toEqual([{collection_id:'custom-two',library_entry_id:'menu-rules-entry'}])
})

test('filters expose crossover modes, removable chips, word count and consistent sizing',async({page},info)=>{
 const tables=await fixture(page)
 for (const [index,fandoms] of [['one',['Alpha']],['cross',['Alpha','Beta']]] as const) {
  tables.works.push({id:`filters-${index}`,ao3_work_id:index==='one'?88003:88004,verified_chapters:{}})
  tables.library_entries.push({id:`entry-${index}`,work_id:`filters-${index}`,original_url:`https://archiveofourown.org/works/${index==='one'?88003:88004}`,reading_status:'reading',last_read_chapter:1,is_favorite:false,notes:'',metadata_overrides:{title:`Filters ${index}`,authors:[],fandoms,word_count:index==='one'?100:200,publication_status:'in_progress',published_chapters:2}})
 }
 await page.goto('/library');await login(page)
 await page.getByRole('button',{name:'Select Fandoms',exact:true}).click()
 const fandom=page.locator('.fandom-panel')
 const box=(await fandom.boundingBox())!
 expect(box.width).toBeGreaterThanOrEqual(info.project.name==='desktop'?560:page.viewportSize()!.width-40)
 expect(box.x).toBeGreaterThanOrEqual(0)
 await page.getByRole('heading',{name:'Your Library',exact:true}).click()
 await page.getByRole('button',{name:'Filters',exact:true}).click()
 const filters=page.getByRole('region',{name:'Library Filters',exact:true})
 const hide=(await filters.getByRole('button',{name:'Hide',exact:true}).boundingBox())!
 for(const button of await filters.locator('.button:not(.filter-default-actions .button), .dropdown-trigger').all()) expect((await button.boundingBox())!.height).toBeCloseTo(hide.height,0)
 for (const button of await filters.locator('.filter-default-actions .button').all()) expect((await button.boundingBox())!.height).toBeGreaterThanOrEqual(48)
 await filters.getByRole('button',{name:'Crossovers',exact:true}).click()
 await page.getByRole('option',{name:'Only',exact:true}).click()
 await page.getByRole('button',{name:'Apply Filters',exact:true}).click()
 await expect(page.locator('.work-card')).toHaveCount(1)
 await page.getByRole('button',{name:'Remove Filter Crossovers Only',exact:true}).click()
 await expect(page.locator('.work-card')).toHaveCount(2)
 await page.getByRole('button',{name:'Sort',exact:true}).click()
 await page.getByRole('option',{name:'Word Count',exact:true}).click()
 await expect(page.locator('.work-card h2 a')).toHaveText(['Filters cross','Filters one'])
 const rec=page.locator('.work-card').first().getByRole('button',{name:'Mark as Rec',exact:true})
 await rec.hover();await expect(rec).toHaveCSS('background-color','rgba(0, 0, 0, 0)')
 const fandomNames=page.locator('.work-card').first().locator('.work-fandoms .metadata-link')
 const boxes=await fandomNames.evaluateAll(elements=>elements.map(element=>element.getBoundingClientRect().y))
 expect(boxes[0]).toBe(boxes[1])
})
