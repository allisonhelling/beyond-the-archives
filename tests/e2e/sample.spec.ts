test('sample Series collection includes only the first two requested works and saves a private series note', async ({ page }) => {
  const remoteRequests: string[] = []
  await page.route(/https:\/\/(?:[^/]+\.)?(?:supabase\.co|archiveofourown\.org|ao3\.org)\//, route => { remoteRequests.push(route.request().url()); return route.abort() })
  await page.goto('/library?shelf=series')
  const card = page.locator('.series-card')
  await expect(card).toHaveCount(1)
  await expect(card.getByRole('link', { name: 'play it again', exact: true })).toBeVisible()
  await expect(card).toContainText('metisket')
  await expect(card).toContainText('Teen Wolf (TV)')
  await expect(card.locator('.series-work-title')).toHaveText(['Part 1: Play It Again', "Part 2: This Doesn't Hurt"])
  await expect(card.locator('.series-work-list details').first().locator('.story-summary')).toContainText('Stiles goes along with one of Derek’s plans')
  await card.getByRole('link', { name: 'play it again', exact: true }).click()
  await expect(page).toHaveURL(/\/series\/132147$/)
  await expect(page.getByRole('heading', { name: 'play it again', exact: true })).toBeVisible()
  const info = page.getByRole('region', { name: 'Series information' })
  await expect(info).toContainText('2013-06-29')
  await expect(info).toContainText('2020-08-09')
  await expect(page.locator('.details-story-stats')).toContainText('74,696')
  await expect(page.locator('.details-story-stats')).toContainText('3 works total · 2 in your library')
  const works = page.getByRole('region', { name: 'Works in series' })
  await expect(works.locator('.story-card')).toHaveCount(2)
  await expect(works.locator('.story-card h2 a')).toHaveText(['Play It Again', "This Doesn't Hurt"])
  await page.getByRole('button', { name: 'Add a note', exact: true }).click()
  await page.getByRole('textbox', { name: 'Private notes', exact: true }).fill('Start with part one.')
  await page.locator('.inline-personal-form').getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.locator('.inline-personal-form')).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'Private notes' }).locator('p.story-summary')).toHaveText('Start with part one.')
  await page.reload()
  await expect(page.getByText('Start with part one.', { exact: true })).toBeVisible()
  for (const path of ['/library', '/reading', '/stats', '/features']) {
    await page.goto(path)
    await expect(page.locator('main')).not.toContainText('YOUR PRIVATE READING SPACE')
    await expect(page.locator('main')).not.toContainText('BUILT WITH INTENTION')
  }
  expect(remoteRequests).toEqual([])
})

