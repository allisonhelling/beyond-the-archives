test('finishing a series leaves missing works absent and recalculates status when one is added', async ({ page }) => {
 await page.goto('/library?shelf=series')
 await expect(page.locator('.series-card')).toHaveCount(1)
 await page.locator('.series-card').getByRole('button', {name:'Mark favorite',exact:true}).click()
 await expect(page.locator('.series-card').getByRole('button', {name:'Unmark favorite',exact:true})).toBeVisible()
 const removed = await page.evaluate(() => {
  const key = 'between-chapters:sample-library:v1', library = JSON.parse(localStorage.getItem(key)!)
  const work = library.stories.find((story: {work:{ao3_work_id:number}}) => story.work.ao3_work_id === 2034597)
  library.stories = library.stories.filter((story: {id:string}) => story.id !== work.id)
  localStorage.setItem(key, JSON.stringify(library))
  return work
 })
 await page.goto('/series/132147')
 const panel = page.getByRole('region', {name:'Reading and organization',exact:true})
 await panel.getByRole('button', {name:'Mark as Finished',exact:true}).click()
 const confirm = page.getByRole('dialog', {name:'Finish series?',exact:true})
 await expect(confirm).toContainText('all its works in your library')
 await confirm.getByRole('button', {name:'Mark as finished',exact:true}).click()
 await expect(confirm).toHaveCount(0)
 await expect(panel.locator('.series-reading-status')).toHaveText('Finished')
 await expect(panel.getByRole('button', {name:/^(Mark as Finished|Finished)$/})).toHaveCount(0)
 await expect(page.locator('.details-story-stats')).toContainText('1 in your library')
 await page.reload()
 await expect(panel.locator('.series-reading-status')).toHaveText('Finished')
 await expect(panel.getByRole('button', {name:/^(Mark as Finished|Finished)$/})).toHaveCount(0)
 await page.evaluate(work => {
  const key = 'between-chapters:sample-library:v1', library = JSON.parse(localStorage.getItem(key)!)
  if (library.stories.some((story: {id:string}) => story.id === work.id)) throw new Error('Finish added the missing work')
  library.stories.push({...work,reading_status:'to_read',last_read_chapter:0})
  localStorage.setItem(key, JSON.stringify(library))
 }, removed)
 await page.reload()
 await expect(panel.locator('.series-reading-status')).toHaveText('Currently Reading')
 await expect(panel.getByRole('button', {name:'Mark as Finished',exact:true})).toBeVisible()
 await expect(page.locator('.details-story-stats')).toContainText('2 in your library')
 await page.goto('/library?shelf=currently_reading')
 await expect(page.locator('.series-card .series-reading-status')).toHaveText('Currently Reading')
})
