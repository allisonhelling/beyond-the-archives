import { expect, test } from '@playwright/test'
import { fixture, login } from './library-fixture'

test('shows recorded stats, navigates periods, applies profile controls, and saves reading speed', async ({ page }, testInfo) => {
 const tables = await fixture(page)
 const metadata = { title: 'Stats Fic', authors: ['Stats Author'], fandoms: ['Stats Fandom'], rating: 'Mature', word_count: 2000, published_chapters: 2, total_chapters: 2, publication_status: 'complete', categories: ['Gen'], character_tags: ['Stats Character'], relationship_tags: [], additional_tags: ['Found Family'], ao3_tags: [], summary: '' }
 const chapter = (id: string, position: number, at: string, reread: boolean) => ({ id, action: 'chapter_read', chapter: position, chapter_id: null, at, word_count: 1000, is_reread: reread, status: 'finished' })
 tables.works.push({ id: 'stats-work', ao3_work_id: 123, verified_chapters: {} })
 tables.library_entries.push({ id: 'stats-entry', work_id: 'stats-work', original_url: 'https://archiveofourown.org/works/123', metadata_overrides: metadata, personal_rating: 5, reading_status: 'finished', last_read_chapter: 2, is_favorite: true, notes: '', created_at: '2026-10-01T12:00:00', updated_at: '2026-10-15T12:00:00', reading_history: [chapter('first', 1, '2026-10-02T12:00:00', false), chapter('second', 2, '2026-10-03T12:00:00', false), chapter('repeat', 1, '2026-10-15T12:00:00', true)] })
 await page.goto('/stats')
 await login(page)
 await expect(page.getByRole('heading', { name: 'Reading Stats', exact: true })).toBeVisible()
 const input = page.getByLabel('Exact Month and Year', { exact: false })
 await input.fill('10/2026')
 await page.getByRole('button', { name: 'Go', exact: true }).click()
 const metric = (name: string) => page.locator('.stats-metric').filter({ has: page.getByRole('heading', { name, exact: true }) }).locator('strong')
 await expect(metric('Total Words Read')).toHaveText('3,000')
 await expect(metric('Unique Words Read')).toHaveText('2,000')
 await expect(metric('Re-Read Words')).toHaveText('1,000')
 await page.screenshot({ path: `/tmp/ao3-stats-${testInfo.project.name}.png`, fullPage: true })
 await expect(page.getByRole('heading', { name: 'Daily Word Velocity', exact: true })).toBeVisible()
 await page.getByRole('button', { name: 'Previous Period' }).click()
 await expect(metric('Total Words Read')).toHaveText('0')
 await expect(page.getByRole('heading', { name: 'No Chapter Activity Yet' })).toBeVisible()
 await page.getByRole('button', { name: 'Next Period' }).click()
 await page.getByLabel('Calculate By').selectOption('words')
 await page.getByLabel('Include Re-Reads', { exact: true }).uncheck()
 const fandoms = page.locator('.stats-breakdown').filter({ has: page.getByRole('heading', { name: 'Fandoms', exact: true }) })
 await expect(fandoms).toContainText('2,000 words')
 await page.getByRole('combobox', { name: 'View', exact: true }).selectOption('yearly')
 await expect(page.getByRole('heading', { name: 'Monthly Reading Volume' })).toBeVisible()
 await page.getByRole('button', { name: 'Choose Period' }).click()
 await expect(page.getByRole('dialog', { name: 'Choose a Year' })).toBeVisible()
 await page.getByRole('button', { name: '2025', exact: true }).click()
 await expect(metric('Total Words Read')).toHaveText('0')
 await page.getByLabel('Exact Year', { exact: false }).fill('2026')
 await page.getByRole('button', { name: 'Go', exact: true }).click()
 await expect(metric('Total Words Read')).toHaveText('3,000')
 expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
 await page.getByRole('link', { name: 'Change Reading Speed' }).click()
 await page.getByLabel('Reading Speed (Words per Minute)').fill('300')
 await page.getByRole('button', { name: 'Save Reading Speed' }).click()
 await expect(page.getByRole('status').filter({ hasText: 'Reading speed saved' })).toBeVisible()
 await page.goto('/stats')
 await page.getByLabel('Exact Month and Year', { exact: false }).fill('10/2026')
 await page.getByRole('button', { name: 'Go', exact: true }).click()
 await expect(metric('Estimated Reading Time')).toHaveText('0h 10m')
 await page.evaluate(() => localStorage.setItem('between-chapters:date-format:v1', 'YMD'))
 await page.reload()
 await page.getByLabel('Exact Month and Year', { exact: false }).fill('2026-10')
 await page.getByRole('button', { name: 'Go', exact: true }).click()
 await expect(metric('Total Words Read')).toHaveText('3,000')
 await page.getByRole('button', { name: 'Choose Period' }).click()
 await expect(page.getByRole('dialog', { name: 'Choose a Month' })).toBeVisible()
 await page.getByRole('button', { name: 'September', exact: true }).click()
 await expect(metric('Total Words Read')).toHaveText('0')
})
