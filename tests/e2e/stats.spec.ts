import { expect, test } from '@playwright/test'
import { fixture, login } from './library-fixture'

test('shows recorded stats, navigates periods, applies profile controls, and saves reading speed', async ({ page }, testInfo) => {
 const tables = await fixture(page)
 const metadata = { title: 'Stats Fic', authors: ['Stats Author'], fandoms: ['Stats Fandom'], rating: 'Mature', word_count: 2000, published_chapters: 2, total_chapters: 2, publication_status: 'complete', categories: ['Gen'], character_tags: ['Stats Character'], relationship_tags: [], additional_tags: ['Found Family'], ao3_tags: [], summary: '' }
 const chapter = (id: string, position: number, at: string, reread: boolean) => ({ id, action: 'chapter_read', chapter: position, chapter_id: null, at, word_count: 1000, is_reread: reread, status: 'finished' })
 tables.works.push({ id: 'stats-work', ao3_work_id: 123, verified_chapters: {} })
 tables.library_entries.push({ id: 'stats-entry', work_id: 'stats-work', original_url: 'https://archiveofourown.org/works/123', metadata_overrides: metadata, personal_rating: 5, reading_status: 'finished', last_read_chapter: 2, is_favorite: true, notes: '', created_at: '2026-10-01T12:00:00', updated_at: '2026-10-15T12:00:00', reading_history: [chapter('first', 1, '2026-10-02T12:00:00', false), chapter('second', 2, '2026-10-03T12:00:00', false), chapter('repeat', 1, '2026-10-15T12:00:00', true)] })
 tables.works.push({ id: 'stats-old-work', ao3_work_id: 124, verified_chapters: {} })
 tables.library_entries.push({ id: 'stats-old-entry', work_id: 'stats-old-work', original_url: 'https://archiveofourown.org/works/124', metadata_overrides: { ...metadata, title: 'Earlier Fic', fandoms: ['Earlier Fandom'], word_count: 500, published_chapters: 1, total_chapters: 1 }, personal_rating: 4, reading_status: 'finished', last_read_chapter: 1, is_favorite: false, notes: '', created_at: '2025-10-01T12:00:00', updated_at: '2025-10-15T12:00:00', reading_history: [{ ...chapter('older', 1, '2025-10-15T12:00:00', false), word_count: 500 }] })
 await page.goto('/stats')
 await login(page)
 await expect(page.getByRole('heading', { name: 'Reading Stats', exact: true })).toBeVisible()
 await expect(page.getByText('Your reading, in perspective.', { exact: true })).toHaveCount(0)
 const tabs = page.getByRole('tablist', { name: 'Reading Statistics Sections' })
 await expect(tabs.getByRole('tab')).toHaveText(['Volume & Progress', 'Your Reading Profile', 'Favorites & Familiar Worlds', 'Reading Habits', 'Trends Over Time'])
 const openSection = async (name: string) => {
  await tabs.getByRole('tab', { name, exact: true }).click()
  await expect(tabs.getByRole('tab', { name, exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('tabpanel')).toHaveCount(1)
 }
 await tabs.getByRole('tab', { name: 'Volume & Progress', exact: true }).focus()
 await page.keyboard.press('ArrowRight')
 await expect(tabs.getByRole('tab', { name: 'Your Reading Profile', exact: true })).toBeFocused()
 await expect(page.getByRole('heading', { name: 'Your Reading Profile', exact: true })).toBeVisible()
 await expect(page.getByRole('heading', { name: 'Volume & Progress', exact: true })).toHaveCount(0)
 await page.keyboard.press('End')
 await expect(tabs.getByRole('tab', { name: 'Trends Over Time', exact: true })).toBeFocused()
 await page.keyboard.press('ArrowLeft')
 await expect(tabs.getByRole('tab', { name: 'Reading Habits', exact: true })).toBeFocused()
 await page.keyboard.press('ArrowRight')
 await page.keyboard.press('ArrowRight')
 await expect(tabs.getByRole('tab', { name: 'Volume & Progress', exact: true })).toBeFocused()
 await page.keyboard.press('End')
 await page.keyboard.press('Home')
 await expect(tabs.getByRole('tab', { name: 'Volume & Progress', exact: true })).toHaveAttribute('aria-selected', 'true')
 async function enterPeriod(value: string, yearly = false) {
  await page.locator('.stats-period-label').click()
  const dialog = page.getByRole('dialog', { name: yearly ? 'Choose a Year' : 'Choose a Month' })
  const input = dialog.getByLabel(yearly ? 'Exact Year' : 'Exact Month and Year', { exact: false })
  await expect(input).toBeFocused()
  await input.fill(value)
  await input.press('Enter')
  await expect(dialog).toHaveCount(0)
 }
 await expect(page.getByLabel('Exact Month and Year', { exact: false })).toHaveCount(0)
 await expect(page.getByRole('button', { name: 'Calendar', exact: true })).toHaveCount(0)
 await enterPeriod('10/2026')
 const dateButton = page.getByRole('button', { name: 'October 2026', exact: true })
 const calendar = page.getByRole('button', { name: 'Choose Period' })
 await expect(calendar).toHaveText('')
 const labelBox = (await dateButton.boundingBox())!, calendarBox = (await calendar.boundingBox())!
 expect(calendarBox.x).toBeGreaterThanOrEqual(labelBox.x + labelBox.width)
 await expect(page.getByRole('button', { name: 'Today', exact: true })).toHaveAttribute('title', 'Go to current month')
 await expect(page.getByRole('button', { name: 'Today', exact: true }).locator('svg')).toHaveCount(1)
 await dateButton.click()
 const invalidDate = page.getByLabel('Exact Month and Year', { exact: false })
 await invalidDate.fill('13/2026')
 await invalidDate.press('Enter')
 await expect(page.getByRole('alert')).toContainText('Enter a valid mm/yyyy')
 await page.keyboard.press('Escape')
 await expect(dateButton).toBeFocused()
 const metric = (name: string) => page.locator('.stats-metric').filter({ has: page.getByRole('heading', { name, exact: true }) }).locator('strong')
 await expect(metric('Total Words Read')).toHaveText('3,000')
 await expect(metric('Unique Words Read')).toHaveText('2,000')
 await expect(metric('Re-Read Words')).toHaveText('1,000')
 const info = page.getByRole('button', { name: 'Total Words Read Information' })
 const explanation = 'Word totals count completed chapters, rather than the full length of partially read works. Unknown chapter word counts are excluded.'
 await expect(info).toHaveAccessibleDescription(explanation)
 const tooltip = page.locator(`[id="${await info.getAttribute('aria-describedby')}"]`)
 await expect(tooltip).toBeHidden()
 await info.click()
 await expect(tooltip).toBeVisible()
 await page.keyboard.press('Escape')
 await expect(tooltip).toBeHidden()
 const estimated = page.locator('.stats-metric').filter({ has: page.getByRole('heading', { name: 'Estimated Reading Time', exact: true }) })
 const speedLink = estimated.getByRole('link', { name: 'Change Reading Speed' })
 await expect(speedLink).toBeVisible()
 expect((await speedLink.boundingBox())!.y).toBeGreaterThan((await estimated.locator('p').boundingBox())!.y)
 if (testInfo.project.name === 'desktop') {
  await speedLink.hover()
  await expect(speedLink).toHaveCSS('text-decoration-line', 'underline')
 }
 await speedLink.focus()
 await expect(speedLink).toHaveCSS('text-decoration-line', 'underline')
 await page.screenshot({ path: `/tmp/ao3-stats-${testInfo.project.name}.png`, fullPage: true })
 await openSection('Reading Habits')
 await expect(page.getByRole('heading', { name: 'Daily Word Velocity', exact: true })).toBeVisible()
 await openSection('Volume & Progress')
 await page.getByRole('button', { name: 'Previous Period' }).click()
 await expect(metric('Total Words Read')).toHaveText('0')
 await expect(page.getByRole('heading', { name: 'No Chapter Activity Yet' })).toBeVisible()
 await page.getByRole('button', { name: 'Next Period' }).click()
 await openSection('Your Reading Profile')
 await page.getByLabel('Calculate By').selectOption('words')
 await page.getByLabel('Include Re-Reads', { exact: true }).uncheck()
 const fandoms = page.locator('.stats-breakdown').filter({ has: page.getByRole('heading', { name: 'Fandoms', exact: true }) })
 await expect(fandoms).toContainText('2,000 words')
 await page.getByRole('combobox', { name: 'View', exact: true }).selectOption('yearly')
 await openSection('Reading Habits')
 await expect(page.getByRole('heading', { name: 'Monthly Reading Volume' })).toBeVisible()
 await openSection('Volume & Progress')
 await page.getByRole('button', { name: 'Choose Period' }).click()
 await expect(page.getByRole('dialog', { name: 'Choose a Year' })).toBeVisible()
 await page.getByRole('button', { name: '2025', exact: true }).click()
 await expect(metric('Total Words Read')).toHaveText('500')
 await page.getByRole('button', { name: 'Today', exact: true }).click()
 await expect(page.getByRole('combobox', { name: 'View', exact: true })).toHaveValue('yearly')
 await expect(page.locator('.stats-period-label')).toHaveText(String(await page.evaluate(() => new Date().getFullYear())))
 await enterPeriod('2026', true)
 await expect(page.getByRole('button', { name: 'Today', exact: true })).toHaveAttribute('title', 'Go to current year')
 await expect(metric('Total Words Read')).toHaveText('3,000')
 await page.getByRole('combobox', { name: 'View', exact: true }).selectOption('all_time')
 await expect(metric('Total Words Read')).toHaveText('3,500')
 await expect(metric('Unique Words Read')).toHaveText('2,500')
 await expect(metric('Fics Read')).toHaveText('2')
 await openSection('Reading Habits')
 await expect(page.getByRole('heading', { name: 'Yearly Reading Volume' })).toBeVisible()
 await expect(page.getByRole('heading', { name: /^Compared With/ })).toHaveCount(0)
 await expect(page.getByRole('button', { name: 'Choose Period' })).toHaveCount(0)
 await openSection('Favorites & Familiar Worlds')
 await expect(page.getByRole('heading', { name: 'Most Re-Read Fics', exact: true })).toBeVisible()
 await openSection('Your Reading Profile')
 await expect(page.getByLabel('Calculate By')).toHaveValue('words')
 await expect(page.getByLabel('Include Re-Reads', { exact: true })).not.toBeChecked()
 await expect(fandoms).toContainText('Earlier Fandom')
 await openSection('Trends Over Time')
 await expect(page.getByRole('columnheader', { name: '2025', exact: true })).toBeVisible()
 await expect(page.getByRole('columnheader', { name: '2026', exact: true })).toBeVisible()
 await page.getByRole('button', { name: 'Today', exact: true }).click()
 await expect(page.getByRole('combobox', { name: 'View', exact: true })).toHaveValue('monthly')
 const current = await page.evaluate(() => new Date().toLocaleString('en-US', { month: 'long', year: 'numeric' }))
 await expect(page.locator('.stats-period-label')).toHaveText(current)
 expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
 await openSection('Volume & Progress')
 await page.getByRole('link', { name: 'Change Reading Speed' }).click()
 await page.getByLabel('Reading Speed (Words per Minute)').fill('300')
 await page.getByRole('button', { name: 'Save Reading Speed' }).click()
 await expect(page.getByRole('status').filter({ hasText: 'Reading speed saved' })).toBeVisible()
 await page.goto('/stats')
 await enterPeriod('10/2026')
 await expect(metric('Estimated Reading Time')).toHaveText('0h 10m')
 await page.evaluate(() => localStorage.setItem('between-chapters:date-format:v1', 'YMD'))
 await page.reload()
 await enterPeriod('2026-10')
 await expect(metric('Total Words Read')).toHaveText('3,000')
 await page.getByRole('button', { name: 'Choose Period' }).click()
 await expect(page.getByRole('dialog', { name: 'Choose a Month' })).toBeVisible()
 await page.getByRole('button', { name: 'September', exact: true }).click()
 await expect(metric('Total Words Read')).toHaveText('0')
})
