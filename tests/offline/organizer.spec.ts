import { expect, test } from '@playwright/test'
import { blankMetadata } from '../../src/features/library/model'
test('cold starts a cached hub, filters retained tiles, and hands off identifiers without server lookups', async ({ page, context }) => {
  await page.goto('/')
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  const snapshot = { userId: 'account', savedAt: '2026-10-29T12:00:00Z', cloudBooks: [{ id: 'a'.repeat(64), workId: '8002', metadata: { ...blankMetadata, title: 'Cloud Story', authors: ['Cloud Writer'] }, status: 'to_read', notes: '', completedCount: 0 }], readers: [{ id: 'installation', name: 'Laptop Reader', url: 'https://reader.example/', reportedAt: '2026-10-29T12:00:00Z', works: ['8001'] }], stories: [{ id: 'work', detailsLoaded: true, metadata: { ...blankMetadata, title: 'Cached Story', authors: ['Writer'], fandoms: ['Fandom'] }, work: { ao3_work_id: 8001, verified_chapters: {} }, collectionIds: [], personalTags: [], reading_status: 'reading', last_read_chapter: 0, notes: '', created_at: '2026-10-29T12:00:00Z', original_url: 'https://archiveofourown.org/works/8001' }] }
  await page.evaluate(snapshot => localStorage.setItem('bta:offline-hub:v1', JSON.stringify(snapshot)), snapshot)
  await page.close()
  await context.setOffline(true)
  const offline = await context.newPage()
  const errors: string[] = []; offline.on('pageerror', error => errors.push(error.message))
  await offline.goto('/library')
  await expect(offline.getByRole('heading', { name: 'Offline', exact: true })).toBeVisible()
  await expect(offline.getByRole('heading', { name: 'Cached Story', exact: true })).toBeVisible()
  await expect(offline.getByRole('heading', { name: 'Cloud Story', exact: true })).toBeVisible()
  await expect(offline.locator('.story-card').filter({has:offline.getByRole('heading',{name:'Cloud Story',exact:true})}).getByRole('link', { name: 'Read Chapter 1 in EPUB', exact: true })).toHaveAttribute('href', 'https://reader.example/?work=8002&chapter=1')
  const cloudTile=offline.locator('.story-card').filter({has:offline.getByRole('heading',{name:'Cloud Story',exact:true})})
  await cloudTile.getByRole('button',{name:'Mark Favorite',exact:true}).click()
  await cloudTile.getByRole('button',{name:'Mark as Rec',exact:true}).click()
  await offline.reload()
  await expect(cloudTile.getByRole('button',{name:'Unmark Favorite',exact:true})).toHaveAttribute('aria-pressed','true')
  await expect(cloudTile.getByRole('button',{name:'Remove Rec',exact:true})).toHaveAttribute('aria-pressed','true')
  await expect(offline.getByRole('button', { name: 'Disconnect Reader', exact: true })).toBeDisabled()
  await offline.getByText('Installation Reports (1)', { exact: true }).click()
  await expect(offline.getByText(/Laptop Reader · Last reported:/)).toBeVisible()
  await expect(offline.locator('.story-card').filter({has:offline.getByRole('heading',{name:'Cached Story',exact:true})}).getByRole('link', { name: 'Read Chapter 1 in EPUB', exact: true })).toHaveAttribute('href', 'https://reader.example/?work=8001&chapter=1')
  await expect(offline.locator('.book-spine-footer')).toHaveCount(2)
  const toolbar = offline.getByRole('region', { name: 'Library Toolbar', exact: true })
  await toolbar.getByRole('button', { name: 'Select Fandoms' }).click()
  await offline.getByRole('checkbox', { name: 'Fandom (1)', exact: true }).check()
  await offline.getByRole('tab', { name: 'All', exact: true }).click()
  await offline.getByRole('tab', { name: 'Custom', exact: true }).click()
  await expect(offline.locator('.story-card')).toHaveCount(2)
  await toolbar.getByRole('button', { name: 'Apply Filters' }).click()
  await expect(offline.locator('.story-card')).toHaveCount(1)
  await expect(offline.getByLabel('Active Filters')).toContainText('Custom · 1 Groups')
  await offline.reload()
  await expect(offline.locator('.story-card')).toHaveCount(1)
  await offline.getByRole('button', { name: 'Clear All Filters', exact: true }).first().click()
  await expect(offline.locator('.story-card')).toHaveCount(2)
  await offline.getByRole('searchbox', { name: 'Search Title or Author', exact: true }).fill('Missing')
  await offline.getByRole('button', { name: 'Apply Filters', exact: true }).click()
  await expect(offline.locator('.story-card')).toHaveCount(0)
  await offline.getByRole('searchbox', { name: 'Search Title or Author', exact: true }).fill('Cached')
  await offline.getByRole('button', { name: 'Apply Filters', exact: true }).click()
  await expect(offline.locator('.story-card')).toHaveCount(1)
  await offline.setViewportSize({ width: 390, height: 844 })
  expect(await offline.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(errors).toEqual([])
})
test('does not claim an uncached installation can start offline', async ({ browser }) => {
  const context = await browser.newContext({ offline: true })
  const page = await context.newPage()
  await expect(page.goto('http://127.0.0.1:4183/')).rejects.toThrow()
  await context.close()
})
